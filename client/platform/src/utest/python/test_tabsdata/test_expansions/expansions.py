from __future__ import annotations

import ast
import importlib
import sys
from pathlib import Path
from types import ModuleType

STUB_BANNER = "# This file is automatically generated by pyo3_stub_gen"

LIBRARIES = (
    "tabsdata.expansions.foundation",
    "tabsdata.expansions.tableframe",
    "tabsdata.expansions.extensions.tableframe",
)


def libraries() -> list[ModuleType]:
    return [importlib.import_module(library) for library in LIBRARIES]


def native_modules() -> dict[str, ModuleType]:
    libraries()
    return {
        name: module
        for name, module in sorted(sys.modules.items())
        if module is not None
        and any(name.startswith(f"{library}.") for library in LIBRARIES)
        and not name.rsplit(".", 1)[-1].startswith("_")
        and getattr(module, "__file__", None) is None
        and not hasattr(module, "__path__")
        and not all(isinstance(value, ModuleType) for value in public_values(module))
    }


def stub_path(name: str) -> Path | None:
    for library in libraries():
        prefix = f"{library.__name__}."
        if not name.startswith(prefix):
            continue
        parts = name.removeprefix(prefix).split(".")
        for folder in library.__path__:
            candidate = Path(folder).joinpath(*parts).with_suffix(".pyi")
            if candidate.is_file():
                return candidate
    return None


def generated_stubs() -> dict[str, Path]:
    stubs = {}
    for library in libraries():
        for folder in library.__path__:
            for path in sorted(Path(folder).rglob("*.pyi")):
                if STUB_BANNER not in path.read_text(encoding="utf-8"):
                    continue
                relative = path.relative_to(folder).with_suffix("")
                stubs[".".join((library.__name__, *relative.parts))] = path
    return stubs


def exported(stub: Path) -> list[str]:
    for node in ast.parse(stub.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        ):
            return list(ast.literal_eval(node.value))
    return []


def public(module: ModuleType) -> set[str]:
    return {name for name in vars(module) if not name.startswith("_")}


def public_values(module: ModuleType) -> list[object]:
    return [getattr(module, name) for name in public(module)]
