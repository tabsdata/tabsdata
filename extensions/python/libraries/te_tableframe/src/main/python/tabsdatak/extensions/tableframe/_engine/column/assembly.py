from __future__ import annotations

from typing import TYPE_CHECKING

from tabsdatak.extensions.tableframe._engine.column.registry import registry
from tabsdatak.tableframe._engine.constant.column.prefixes import (
    TD_SYSTEM_COLUMN_PREFIX,
)

if TYPE_CHECKING:
    import polars as pl_


# From a given LazyFrame, expectedly coming from the internals of a TableFrame,
# it selects:
#   - All user columns (no system ($) or connector (@) prefix)
#   - All connector (@) columns
#   - All recognized system ($) columns
# Therefore, all columns with the system ($) prefix that are not recognized as
# system columns are removed, while connector (@) columns -- user columns
# generated by the system -- always remain.
# This way, when joins and similar operations are performed, which might bring
# in system ($) columns from more than one source (polars attaches a
# discriminator suffix to the colliding ones automatically), only the one
# preserving the original name survives.
# As a general rule, system ($) columns are totally system-managed. Therefore,
# dropping (internally) these extra columns is safe, and should produce no
# data loss or inconsistency.
def assemble_system_columns(lf: pl_.LazyFrame) -> pl_.LazyFrame:
    instance = registry()
    target_columns = [
        column
        for column in lf.collect_schema().names()
        if instance.get(column) is not None
        or not column.startswith(TD_SYSTEM_COLUMN_PREFIX)
    ]
    return lf.select(target_columns)
