"""Every cloud backend fixture (s3 / gcs / azureblob), loaded from a descriptor
generated by the real tdx create path. Each stages a SYS_PATH (system) +
BASE_PATH (domain) plus its own credentials."""
from __future__ import annotations

from pathlib import Path

import pytest

from tabsdatax.itest.fixture import backend as common
from tabsdatax.itest.fixture.backends.azureblob import AzureblobDomain, AzureblobSystem
from tabsdatax.itest.fixture.backends.gcs import GcsDomain, GcsSystem
from tabsdatax.itest.fixture.backends.s3 import (
    S3Domain,
    S3System,
    s3_domain,
    s3_system,
)

# slug, SystemCls, DomainCls
CLOUD = [
    ("s3", S3System, S3Domain),
    ("gcs", GcsSystem, GcsDomain),
    ("azureblob", AzureblobSystem, AzureblobDomain),
]
IDS = [c[0] for c in CLOUD]


@pytest.mark.parametrize("slug,Sys,Dom", CLOUD, ids=IDS)
def test_cloud_system(provision, slug, Sys, Dom):
    provision.system(slug, "s")
    obj = common.load("s", Sys)   # construction requires every declared field
    assert isinstance(obj, Sys) and obj.system_type == slug
    assert obj.system_kind == "file" and isinstance(obj.sys_path, Path)


@pytest.mark.parametrize("slug,Sys,Dom", CLOUD, ids=IDS)
def test_cloud_domain(provision, slug, Sys, Dom):
    provision.system(slug, "s")
    provision.domain(slug, "s", "d")
    obj = common.load("d", Dom)
    assert isinstance(obj, Dom) and obj.system_type == slug
    assert isinstance(obj.sys_path, Path) and isinstance(obj.base_path, Path)
    assert obj.model is None and obj.data is None


@pytest.fixture
def s3_ready(provision):
    provision.system("s3", "store")
    provision.domain("s3", "store", "inbox")


@s3_system("store")
@s3_domain("inbox")
def test_cloud_injection(backends, s3_ready):
    store: S3System = backends["store"]
    inbox: S3Domain = backends["inbox"]
    assert store.name == "store" and store.bucket == "x"   # --bucket dummy
    assert inbox.name == "inbox"
