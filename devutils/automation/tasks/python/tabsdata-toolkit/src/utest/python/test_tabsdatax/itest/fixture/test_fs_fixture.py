"""fs fixture + the shared load/validate engine in `backend`, and the
declaration markers that inject declared systems/domains by name.

Happy-path backends are generated by the REAL tdx-system / tdx-domain create
path (conftest `provision`); the engine's error paths use hand-written
descriptors for the specific bad shapes they need."""
from __future__ import annotations

from pathlib import Path

import pytest

from tabsdatax.itest.fixture import backend as common
from tabsdatax.itest.fixture.backends.fs import (
    FsDomain,
    FsSystem,
    fs_domain,
    fs_system,
)
from tabsdatax.itest.tdksystems import descriptor, store

# ---- happy path: load descriptors generated by tdx create -----------------

def test_fs_system(provision):
    provision.system("fs", "my_fs")
    s = common.load("my_fs", FsSystem)
    assert isinstance(s, FsSystem)
    assert (s.name, s.system_type, s.system_kind) == ("my_fs", "fs", "file")
    assert isinstance(s.sys_path, Path)


def test_fs_domain(provision):
    provision.system("fs", "my_fs")
    provision.domain("fs", "my_fs", "inbox")
    d = common.load("inbox", FsDomain)
    assert isinstance(d, FsDomain) and d.name == "inbox"
    assert isinstance(d.base_path, Path)
    assert d.model is None and d.data is None


def test_fs_domain_records_model_and_data(provision):
    # MODEL/DATA land in the descriptor when tdx loads a model; the full data
    # pipeline is covered by the fs_lifecycle itest, so just stamp them here.
    provision.system("fs", "my_fs")
    provision.domain("fs", "my_fs", "inbox")
    descriptor.stamp(store.domain_path("inbox"), name="inbox", started="t",
                     model="world", data="xs")
    d = common.load("inbox", FsDomain)
    assert d.model == "world" and d.data == "xs"


# ---- validation: role / system_type / missing / skip ----------------------

def test_wrong_role_fails(provision):
    descriptor.write_cloud_domain(
        out=str(store.system_path("looks_like_sys")),   # a domain in systems/
        storage_type="fs", system_kind="file", sys_path="/tmp/x",
        sys_path_env=None, base_path="/tmp/x/d", forwarded=[])
    descriptor.stamp(store.system_path("looks_like_sys"), name="looks_like_sys",
                     started="t")
    with pytest.raises(pytest.fail.Exception, match="not a system"):
        common.load("looks_like_sys", FsSystem)


def test_system_type_mismatch_fails(provision):
    descriptor.write_cloud_system(
        out=str(store.system_path("weird")), storage_type="mysteryfs",
        system_kind="file", label="x", sys_path="/tmp/x", sys_path_env=None,
        forwarded=[])
    descriptor.stamp(store.system_path("weird"), name="weird", started="t")
    with pytest.raises(pytest.fail.Exception, match="mysteryfs.*FsSystem"):
        common.load("weird", FsSystem)


def test_missing_backend_fails_by_default(provision, monkeypatch):
    monkeypatch.delenv(common.ON_MISSING_ENV[common.SYSTEM], raising=False)
    with pytest.raises(pytest.fail.Exception, match="not found"):
        common.load("does_not_exist", FsSystem)


def test_missing_backend_skips_when_configured(provision, monkeypatch):
    monkeypatch.setenv(common.ON_MISSING_ENV[common.DOMAIN], "skip")
    with pytest.raises(pytest.skip.Exception):
        common.load("does_not_exist", FsDomain)


def test_skip_backends_by_name(provision, monkeypatch):
    provision.system("fs", "my_fs")
    monkeypatch.setenv(common.SKIP_ENV[common.SYSTEM], "other,my_fs")
    with pytest.raises(pytest.skip.Exception, match="skipped"):
        common.load("my_fs", FsSystem)


# ---- injection via the per-type decorators + the named fixtures -----------

@pytest.fixture
def fs_ready(provision):
    provision.system("fs", "my_fs")
    provision.domain("fs", "my_fs", "inbox")


@fs_system("my_fs")
@fs_domain("inbox")
def test_inject(fs_ready, system_my_fs: FsSystem, domain_inbox: FsDomain):
    assert isinstance(system_my_fs, FsSystem)
    assert isinstance(domain_inbox, FsDomain)
    assert system_my_fs.name == "my_fs" and domain_inbox.name == "inbox"


@pytest.fixture
def multi_ready(provision):
    provision.system("fs", "alpha")
    provision.system("fs", "beta")
    provision.domain("fs", "alpha", "inbox")
    provision.domain("fs", "alpha", "outbox")
    provision.domain("fs", "beta", "archive")


@fs_system("alpha")
@fs_system("beta")
@fs_domain("inbox")
@fs_domain("outbox")
@fs_domain("archive")
def test_inject_multiple_systems_and_domains(
    multi_ready,
    system_alpha: FsSystem,
    system_beta: FsSystem,
    domain_inbox: FsDomain,
    domain_outbox: FsDomain,
    domain_archive: FsDomain,
):
    systems = (system_alpha, system_beta)
    assert all(isinstance(system, FsSystem) for system in systems)
    assert (system_alpha.name, system_beta.name) == ("alpha", "beta")

    domains = (domain_inbox, domain_outbox, domain_archive)
    assert all(isinstance(domain, FsDomain) for domain in domains)
    assert {domain.name for domain in domains} == {"inbox", "outbox", "archive"}


def test_undeclared_backend_fails(request, fs_ready):
    with pytest.raises(pytest.fail.Exception, match="No system 'my_fs' declared"):
        request.getfixturevalue("system_my_fs")
