"""Generate the ``.py`` delegation and ``.pyi`` stubs from a signature report.

Module kinds:

* functions      -> free functions delegating to ``pl.<name>``.
* value class    -> ``Expr`` / Expr namespaces: ``_inner`` wrappers (transparent).
* TableFrame     -> the package ``__init__.py``: subclasses ``EngineFrame`` (the
                    hand-written engine frame), with transparent ops and augmenting
                    ops
                    (``project``/``join``/``group_by``/``drop``/``rename``) that wrap
                    the result and dispatch ``run_hook(op, ...)``; ``_HOOKABLE_OPS``
                    lists the dispatching ops.
* LazyGroupBy    -> ``group_by.py``: ``agg`` (hookable) and group-transparent ops.

Per-op behavior is selected by each symbol's ``hook_name`` from the report
("-" = no hook by default; "project"/"join"/"group_by"/"agg"/"drop"/"rename" set
by the user). The generated code carries NO provenance policy — it only wraps and
dispatches hooks; column lineage etc. lives in hand-written hook modules that the
consumer registers via ``set_hook``/``chain``.
"""

from __future__ import annotations

import datetime
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from ..model.model import Report, Symbol
from ..scan.spec import datatype_names
from .pyi import PyiDoc, canonical_signature, parse_pyi
from .typing_gen import TypingGen

_PYI_CHANGED = "#CHANGED SIGNATURE, VALIDATE/FIX PYDOC"
_PYI_NEW = "#NEW SIGNATURE, CREATE PYDOC"


def _copyright() -> str:
    return f"# Copyright {datetime.date.today().year} Tabsdata Inc."


def _py_header() -> str:
    return f"{_copyright()}\n# GENERATED by tdx_gtableframe — do not edit by hand.\n"


def _pyi_header() -> str:
    return (
        f"{_copyright()}\n"
        "# GENERATED by tdx_gtableframe — stubs; add/maintain docstrings here.\n"
    )


def _test_header() -> str:
    return (
        f"{_copyright()}\n"
        "# GENERATED by tdx_gtableframe — overwritten on regen; "
        "put custom tests in other files.\n"
    )


# Each dispatching hook_name -> (number of source frames, ordered (field, type) of
# the params dict the op passes). Drives both the generated op bodies' contract and
# the per-op hook types emitted into _core/hooks.py. group_by builds a grouper (its
# hook fires at agg time), so it isn't here.
_HOOK_SHAPES: dict[str, tuple[int, list[tuple[str, str]]]] = {
    "project": (1, [("exprs", "tuple"), ("named", "dict"), ("replace_all", "bool")]),
    "join": (
        2,
        [
            ("on", "Any"),
            ("how", "str"),
            ("left_on", "Any"),
            ("right_on", "Any"),
            ("suffix", "str"),
        ],
    ),
    "drop": (1, [("columns", "tuple")]),
    "rename": (1, [("mapping", "Any")]),
    "agg": (
        1,
        [
            ("by", "tuple"),
            ("named_by", "dict"),
            ("aggs", "tuple"),
            ("named_aggs", "dict"),
        ],
    ),
}
_HOOK_NAMES = set(_HOOK_SHAPES)


@dataclass
class GenResult:
    modules: list[str] = field(default_factory=list)
    symbol_count: int = 0
    deferred: dict[str, int] = field(default_factory=dict)
    dropped: dict[str, list[str]] = field(
        default_factory=dict
    )  # Module -> symbols gone from .pyi.
    tests: list[str] = field(
        default_factory=list
    )  # Generated test files (overwritten on regen).


def generate(
    report: Report, root_module: str, root_dir: str, testdir: str | None = None
) -> GenResult:
    base = Path(root_dir).joinpath(*root_module.split("."))
    by_module: dict[str, list[Symbol]] = defaultdict(list)
    result = GenResult()

    whitelisted = [s for s in report.symbols if s.whitelisted]
    for sym in whitelisted:
        by_module[sym.target_module].append(sym)

    # Hookable op-names = the method names of hook-dispatching ops (across modules,
    # e.g. agg is a LazyGroupBy method). Used for TableFrame's _HOOKABLE_OPS manifest.
    hookable = sorted({_member(s) for s in whitelisted if s.hook_name in _HOOK_NAMES})
    # (op-name, hook_name) per hookable op -> the per-op hook types in _core/hooks.py.
    hook_specs = sorted({
        (_member(s), s.hook_name) for s in whitelisted if s.hook_name in _HOOK_NAMES
    })

    # datatypes.py is always emitted (aliased leaf types); it's not a report module
    # but must be a submodule so the __init__ loop imports it (registers passthrough).
    datatypes = datatype_names()
    submodules = sorted(
        {m[len(root_module) + 1 :] for m in by_module if m != root_module}
        | {"datatypes"}
    )

    # No polars/numpy type names leak into the .pyi stubs: rewrite annotations and
    # redefine the polars type aliases we use into <root>._typing. The datatype
    # names are ours too (aliased in datatypes.py), so keep + import them from there.
    our_types = (
        {s.target_class for s in whitelisted if s.target_class}
        | {"TableFrame"}
        | set(datatypes)
    )
    class_module = {
        s.target_class: s.target_module for s in whitelisted if s.target_class
    }
    class_module["TableFrame"] = root_module
    for dt in datatypes:
        class_module[dt] = f"{root_module}.datatypes"
    typing_gen = TypingGen(our_types, class_module, root_module)
    all_aliases: set[str] = set()

    written: list[Path] = []
    base.mkdir(parents=True, exist_ok=True)
    written += _write_core(base, root_module, _render_hook_types(hook_specs))
    written.append(_write_datatypes(base, root_module, datatypes))
    for module, syms in sorted(by_module.items()):
        is_root = module == root_module
        filename = "__init__" if is_root else module[len(root_module) + 1 :]
        py_path = base / f"{filename}.py"
        py_path.write_text(_render_py(syms, root_module, is_root, hookable, submodules))
        written.append(py_path)

        # Regenerate the .pyi, preserving hand-written docstrings: rename any
        # existing stub to a transient .pyi-ori, read it, then drop it.
        pyi_path = base / f"{filename}.pyi"
        previous: PyiDoc | None = None
        if pyi_path.exists():
            ori_path = base / f"{filename}.pyi-ori"
            pyi_path.replace(ori_path)
            try:
                previous = parse_pyi(ori_path.read_text())
            except SyntaxError:
                previous = None  # a corrupt prior stub shouldn't block regeneration
            finally:
                ori_path.unlink()
        text, aliases = _render_pyi(syms, previous, typing_gen, module, root_module)
        pyi_path.write_text(text)
        written.append(pyi_path)
        all_aliases |= aliases
        if previous is not None:
            current = {(s.target_class, _member(s)) for s in syms}
            dropped = sorted(name for (_, name) in set(previous.funcs) - current)
            if dropped:
                result.dropped[module] = dropped

        result.modules.append(module)
        result.symbol_count += len(syms)

    typing_pyi = base / "_typing.pyi"
    typing_pyi.write_text(
        _pyi_header() + "\n" + typing_gen.render_typing_pyi(all_aliases)
    )
    written.append(typing_pyi)

    # Tests are always generated (default dir derived from --root-dir if not given).
    test_dir = testdir or _default_testdir(root_dir, root_module)
    result.tests, test_files = _generate_tests(by_module, root_module, test_dir)
    written += test_files

    _format(written)
    return result


_CORE_MODULES = ("base", "translate", "hooks")


def _write_core(base: Path, root_module: str, hook_types: str) -> list[Path]:
    """Emit the _core runtime (base/translate/hooks) from bundled templates.

    These are the framework runtime, not customization — customization lives in
    registered hooks. Regenerated each run with the root module substituted in;
    hooks.py also gets the per-op hook types (``__HOOK_TYPES__`` placeholder).
    """
    core_dir = base / "_core"
    core_dir.mkdir(parents=True, exist_ok=True)
    templates = Path(__file__).parent / "templates"
    written = []
    for name in _CORE_MODULES:
        text = (
            (templates / f"{name}.py.tmpl")
            .read_text()
            .replace("__ROOT_MODULE__", root_module)
            .replace("__HOOK_TYPES__", hook_types)
        )
        path = core_dir / f"{name}.py"
        path.write_text(_py_header() + "\n" + text)
        written.append(path)
    return written


def _pascal(name: str) -> str:
    return "".join(word.capitalize() for word in name.split("_"))


def _render_hook_types(specs: list[tuple[str, str]]) -> str:
    """Render the per-op hook types for hooks.py: one ``<HookName>Params`` TypedDict
    per distinct hook_name, and one ``<OpName>Hook`` Callable alias per op-name.

    ``specs`` is (op-name, hook_name) per hookable op — e.g. ("with_columns",
    "project"), ("join", "join"). Empty input yields an empty block.
    """
    if not specs:
        return ""
    lines: list[str] = []
    for hook_name in sorted({hn for _, hn in specs}):
        _, fields = _HOOK_SHAPES[hook_name]
        lines += [
            f"class {_pascal(hook_name)}Params(TypedDict):",
            f'    """Params a {hook_name!r} op passes to its hook."""',
            "",
        ]
        lines += [f"    {field}: {type_str}" for field, type_str in fields]
        lines += ["", ""]
    for op_name, hook_name in sorted(specs):
        n_sources, _ = _HOOK_SHAPES[hook_name]
        sources = ", ".join(['"TableFrame"'] * n_sources)
        lines.append(
            f"{_pascal(op_name)}Hook = "
            f'Callable[["TableFrame", tuple[{sources}], '
            f'{_pascal(hook_name)}Params], "TableFrame"]'
        )
    return "\n".join(lines)


def _write_datatypes(base: Path, root_module: str, names: list[str]) -> Path:
    """Emit datatypes.py: alias the public polars datatypes as ours, register
    DataType as a passthrough leaf type (wrap() returns them unchanged), and an
    editable ``_ALLOWED_TYPES`` allow-list enforced via ``_valid_type``."""
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "",
        f"from {root_module}._core.translate import "
        "register_passthrough, register_type_validator",
        "",
    ]
    for name in names:
        lines.append(f"{name} = pl.{name}")
    lines += [
        "",
        "",
        "# The datatypes this API accepts. Defaults to every alias above; remove",
        "# entries to restrict the allowed set. Enforced on datatype arguments and",
        "# on the schema of any LazyFrame entering a TableFrame.",
        "_ALLOWED_TYPES = [",
    ]
    lines += [f"    {name}," for name in names]
    lines += [
        "]",
        "",
        "",
        "def _valid_type(dtype):",
        '    """Assert `dtype` (possibly nested/parametrized) uses only allowed types;',
        '    return it. Raises TypeError on the first disallowed type."""',
        "    base = dtype if isinstance(dtype, type) else type(dtype)",
        "    if base not in _ALLOWED_TYPES:",
        "        raise TypeError(",
        '            f"tableframe: datatype {base.__name__!r} is not allowed "',
        '            f"(see _ALLOWED_TYPES in {__name__})"',
        "        )",
        '    inner = getattr(dtype, "inner", None)  # List / Array element type',
        "    if inner is not None:",
        "        _valid_type(inner)",
        '    for field in getattr(dtype, "fields", None) or ():  # Struct fields',
        "        _valid_type(field.dtype)",
        "    return dtype",
        "",
        "",
        "# Datatypes are aliased leaf types: wrap() returns any DataType unchanged,",
        "# and _valid_type enforces the allow-list wherever a type is set.",
        "register_passthrough(pl.DataType)",
        "register_type_validator(_valid_type)",
    ]
    path = base / "datatypes.py"
    path.write_text("\n".join(lines) + "\n")
    return path


def _default_testdir(root_dir: str, root_module: str) -> str:
    parts = list(Path(root_dir).parts)
    if "main" in parts:  # Maven layout: src/main/python -> src/utest/python
        parts[parts.index("main")] = "utest"
    first, *rest = root_module.split(".")
    return str(Path(*parts).joinpath("test_" + first, *rest, "generator"))


def _format(paths: list[Path]) -> None:
    config = str(Path(__file__).parent / "ruff.toml")
    sources = [str(path) for path in paths]
    # .pyi stubs are formatted but NOT lint-fixed: `ruff check --fix` would strip
    # imports it reads as unused (a stub's names are used only in annotations),
    # breaking the stub. `.py` files get both passes (matches cargo make format_py).
    code = [str(path) for path in paths if path.suffix != ".pyi"]
    commands = [
        [sys.executable, "-m", "ruff", "format", "--config", config, *sources],
    ]
    if code:
        commands.append([
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--fix",
            "--config",
            config,
            *code,
        ])
    for command in commands:
        try:
            subprocess.run(command, check=True, capture_output=True)
        except (FileNotFoundError, subprocess.CalledProcessError):
            pass  # ruff not installed, or a file it couldn't fix — leave as-is


# --------------------------------------------------------------------------- #
# Test generation — mock-spy that each wrapper call reaches polars.
# --------------------------------------------------------------------------- #
def _write_test_namespace_inits(base: Path) -> list[Path]:
    template = Path(__file__).parent / "templates" / "namespace_init.py.tmpl"
    copyright = _copyright().removeprefix("# ")
    text = template.read_text().replace("__COPYRIGHT__", copyright)
    parts = base.parts
    root = parts.index("python") + 1
    written: list[Path] = []
    folder = Path(*parts[:root])
    for part in parts[root:]:
        folder = folder / part
        init = folder / "__init__.py"
        if not init.exists():
            init.write_text(text)
            written.append(init)
    return written


def _generate_tests(
    by_module: dict[str, list[Symbol]], root_module: str, testdir: str
) -> tuple[list[str], list[Path]]:
    base = Path(testdir)
    base.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    paths: list[Path] = _write_test_namespace_inits(base)
    for module, syms in sorted(by_module.items()):
        is_root = module == root_module
        # Test files mirror the module name; the root (an __init__.py) becomes
        # test_<root package>. Same-named files are overwritten; custom tests
        # (other names) are left untouched.
        filename = (
            f"test_{root_module.split('.')[0]}"
            if is_root
            else module[len(root_module) + 1 :]
        )
        path = base / f"{filename}.py"
        path.write_text(_render_test_module(syms, root_module, is_root))
        names.append(filename)
        paths.append(path)
    return names, paths


# Each generated test file pairs a mock test (delegation reaches polars, all ops)
# with a "live" test (best-effort real polars: call with no args, skip if it needs
# args, fail only on a genuine leak). _VALUE_LIVE maps value classes we can build a
# real receiver for; namespaces / when-then are mock-only.
_VALUE_LIVE = {"Expr": 'Expr._wrap(pl.col("a"))'}

# Members whose no-arg live call would block on an interactive GUI or otherwise
# misbehave; the mapped string is spliced in as the live-call arguments so the
# "_runs" smoke test stays headless. show_graph defaults to show=True, which
# opens a blocking matplotlib window under a pytest worker.
_LIVE_ARGS = {"show_graph": "show=False"}


def _live_call(receiver: str, name: str, is_property: bool) -> str:
    if is_property:
        return f"{receiver}.{name}"
    return f"{receiver}.{name}({_LIVE_ARGS.get(name, '')})"


def _live_test(safe: str, result_stmt: str) -> list[str]:
    return [
        "",
        f"def test_{safe}_runs():",
        "    try:",
        f"        {result_stmt}",
        "    except Exception as exc:  # noqa: BLE001",
        '        if "tableframe:" in str(exc):',
        "            raise  # a real leak, not an argument problem",
        '        pytest.skip(f"not callable with simple args: {type(exc).__name__}")',
        '    assert type(result).__module__.split(".", 1)[0] != "polars"',
    ]


def _render_test_module(syms: list[Symbol], root: str, is_root: bool) -> str:
    target_class = syms[0].target_class
    if target_class is None:
        text = _render_functions_test(syms, root)
    elif is_root:
        text = _render_tableframe_test(syms, root)
    elif target_class == "LazyGroupBy":
        text = _render_lazygroupby_test(syms, root)
    else:
        text = _render_value_test(syms, root)
    return _with_test_marker(text)


def _with_test_marker(text: str) -> str:
    lines = text.splitlines()
    if "import pytest" not in lines:
        future = lines.index("from __future__ import annotations")
        lines.insert(future + 1, "import pytest")
    first_def = next(
        i for i, line in enumerate(lines) if line.startswith(("def ", "@"))
    )
    lines[first_def:first_def] = ["pytestmark = pytest.mark.tfgen", "", ""]
    return "\n".join(lines) + "\n"


def _render_value_test(syms: list[Symbol], root: str) -> str:
    groups = _group_by_class(syms)
    multi = (
        len(groups) > 1
    )  # disambiguate test names when a module holds several classes
    has_live = any(c in _VALUE_LIVE for c in groups)
    relative = syms[0].target_module[len(root) + 1 :]
    lines = [_test_header(), "from __future__ import annotations", ""]
    if has_live:
        lines += ["import polars as pl", "import pytest"]
    lines += [
        "from unittest.mock import MagicMock",
        "",
        f"from {root}.{relative} import " + ", ".join(groups),
        "",
    ]
    for cls_name, cls_syms in groups.items():
        prefix = f"{cls_name}_" if multi else ""
        receiver = _VALUE_LIVE.get(cls_name)
        for sym in cls_syms:
            name = _member(sym)
            safe = f"{prefix}{_safe(name)}"
            lines += ["", f"def test_{safe}_delegates():", "    inner = MagicMock()"]
            if sym.is_property:
                lines.append(
                    f"    getattr({cls_name}._wrap(inner), {name!r})"
                )  # accessor wires through
            else:
                arg = "MagicMock()" if name in ("__eq__", "__ne__") else ""
                lines += [
                    f"    getattr({cls_name}._wrap(inner), {name!r})({arg})",
                    f"    getattr(inner, {name!r}).assert_called()",
                ]
            if receiver is not None:
                stmt = f"result = {_live_call(receiver, name, sym.is_property)}"
                lines += _live_test(safe, stmt)
    return "\n".join(lines) + "\n"


def _render_functions_test(syms: list[Symbol], root: str) -> str:
    relative = syms[0].target_module[len(root) + 1 :]
    lines = [
        _test_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "import pytest",
        "from unittest.mock import MagicMock",
        "",
        f"from {root} import {relative} as _module",
        "",
    ]
    for sym in syms:
        name = _member(sym)
        safe = _safe(name)
        lines += [
            "",
            f"def test_{safe}_delegates(monkeypatch):",
            "    spy = MagicMock()",
            f"    monkeypatch.setattr(pl, {name!r}, spy)",
            f"    _module.{name}()",
            "    spy.assert_called()",
        ]
        lines += _live_test(
            safe, f"result = {_live_call('_module', name, sym.is_property)}"
        )
    return "\n".join(lines) + "\n"


def _render_tableframe_test(syms: list[Symbol], root: str) -> str:
    lines = [
        _test_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "import pytest",
        "from unittest.mock import MagicMock",
        "",
        f"from {root} import TableFrame",
        f"from {root}._core.hooks import tableframe_of",
        f"from {root}._engine.model.tableframe import TableFrameState",
        "",
        "",
        "def _frame():",
        "    grant = {TableFrame._ACCESS_KEY: TableFrame._ACCESS_SECRET}",
        "    frame = TableFrame.__new__(TableFrame, **grant)",
        "    frame._lf = MagicMock()",
        "    frame._state = TableFrameState.empty()",
        "    return frame",
        "",
        "",
        "def _live_frame():",
        '    return tableframe_of(pl.LazyFrame({"a": [1.0], "b": [2.0]}))',
    ]
    for sym in syms:
        name = _member(sym)
        safe = _safe(name)
        lines += ["", f"def test_{safe}_delegates():", "    frame = _frame()"]
        if sym.is_property:
            lines.append(f"    assert frame.{name} is frame._lf.{name}")
        else:
            if sym.hook_name == "join":
                call = f"frame.{name}(_frame())"
            elif sym.hook_name == "rename":
                call = f"frame.{name}({{}})"
            elif name in ("__eq__", "__ne__"):
                call = f"frame.{name}(MagicMock())"
            else:
                call = f"frame.{name}()"
            lines += [f"    {call}", f"    frame._lf.{name}.assert_called()"]
        stmt = f"result = {_live_call('_live_frame()', name, sym.is_property)}"
        lines += _live_test(safe, stmt)
    return "\n".join(lines) + "\n"


def _render_lazygroupby_test(syms: list[Symbol], root: str) -> str:
    lines = [
        _test_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "import pytest",
        "from unittest.mock import MagicMock",
        "",
        f"from {root} import TableFrame",
        f"from {root}._core.hooks import tableframe_of",
        f"from {root}._engine.model.tableframe import TableFrameState",
        f"from {root}.group_by import LazyGroupBy",
        "",
        "",
        "def _group_by():",
        "    grant = {TableFrame._ACCESS_KEY: TableFrame._ACCESS_SECRET}",
        "    parent = TableFrame.__new__(TableFrame, **grant)",
        "    parent._lf = MagicMock()",
        "    parent._state = TableFrameState.empty()",
        "    return LazyGroupBy(MagicMock(), parent, ((), {}))",
        "",
        "",
        "def _live_group_by():",
        "    return tableframe_of(pl.LazyFrame("
        '{"a": [1.0], "b": [2.0]})).group_by("a")',
    ]
    for sym in syms:
        name = _member(sym)
        safe = _safe(name)
        lines += [
            "",
            f"def test_{safe}_delegates():",
            "    group_by = _group_by()",
            f"    group_by.{name}()",
            f"    group_by._lgb.{name}.assert_called()",
        ]
        lines += _live_test(
            safe,
            f"result = {_live_call('_live_group_by()', name, sym.is_property)}",
        )
    return "\n".join(lines) + "\n"


def _safe(name: str) -> str:
    # dunders -> op_<core> so e.g. __abs__ doesn't collide with the method abs
    if name.startswith("__") and name.endswith("__"):
        return "op_" + name.strip("_")
    return name


# --------------------------------------------------------------------------- #
# .py rendering — dispatch by module kind.
# --------------------------------------------------------------------------- #
def _render_py(
    syms: list[Symbol],
    root: str,
    is_root: bool,
    hookable: list[str],
    submodules: list[str],
) -> str:
    target_class = syms[0].target_class
    if target_class is None:
        return _render_functions_py(syms, root)
    if is_root:
        return _render_tableframe_py(syms, root, hookable, submodules)
    if target_class == "LazyGroupBy":
        return _render_lazygroupby_py(syms, root)
    return _render_value_class_py(syms, root)


def _render_functions_py(syms: list[Symbol], root: str) -> str:
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "",
        f"from {root}._core.translate import unwrap, wrap",
        "",
    ]
    for sym in syms:
        name = _member(sym)
        lines += [
            "",
            f"def {name}(*args, **kwargs):",
            f"    return wrap(pl.{name}(*unwrap(args), **unwrap(kwargs)))",
        ]
    return "\n".join(lines) + "\n"


def _render_value_class_py(syms: list[Symbol], root: str) -> str:
    groups = _group_by_class(syms)  # a module may hold several classes (e.g. whenthen)
    lines = [_py_header(), "from __future__ import annotations", ""]
    for cls_syms in groups.values():
        pl_module, pl_class = _polars_class(cls_syms[0])
        lines.append(f"from {pl_module} import {pl_class} as _Pl{pl_class}")
    lines += [
        f"from {root}._core.base import BaseWrapper",
        f"from {root}._core.translate import register, unwrap, wrap",
    ]
    for cls_name, cls_syms in groups.items():
        _, pl_class = _polars_class(cls_syms[0])
        lines += [
            "",
            "",
            f"@register(_Pl{pl_class})",
            f"class {cls_name}(BaseWrapper):",
        ]
        for sym in cls_syms:
            name = _member(sym)
            if sym.is_property:
                lines += [
                    "    @property",
                    f"    def {name}(self):",
                    f"        return wrap(self._inner.{name})",
                    "",
                ]
            else:
                lines += [
                    f"    def {name}(self, *args, **kwargs):",
                    f"        return wrap("
                    f"self._inner.{name}(*unwrap(args), **unwrap(kwargs)))",
                    "",
                ]
    return "\n".join(lines) + "\n"


def _group_by_class(syms: list[Symbol]) -> "dict[str, list[Symbol]]":
    groups: dict[str, list[Symbol]] = {}
    for sym in syms:
        groups.setdefault(sym.target_class, []).append(sym)
    return groups


def _render_tableframe_py(
    syms: list[Symbol], root: str, hookable: list[str], submodules: list[str]
) -> str:
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        f"from {root}._core.hooks import run_hook",
        f"from {root}._core.translate import register_loader, unwrap, wrap",
        f"from {root}._engine.frame.frame import EngineFrame",
        "",
        "",
        "class TableFrame(EngineFrame):",
    ]
    if hookable:
        lines.append(f"    _HOOKABLE_OPS = ({', '.join(repr(op) for op in hookable)},)")
        lines.append("")
    for sym in syms:
        lines += _tableframe_member(sym, root)

    # Lazy registry population. Importing this package must NOT drag in polars
    # (a heavy import); so the registry-filling loop — importing every submodule
    # for its @register side-effects, then mapping LazyFrame -> TableFrame so
    # frame-returning ops never leak a raw pl.LazyFrame — is deferred into
    # _load_registry(), which translate calls on first actual use (first wrap miss
    # / first frame construction). At import we only register the loader (cheap).
    lines += [
        "",
        "",
        "def _load_registry() -> None:",
        "    import importlib",
        "    import polars as pl",
        "",
        f"    for submodule in {tuple(submodules)!r}:",
        '        importlib.import_module(f"{__name__}.{submodule}")',
        "",
        f"    from {root}._core.translate import register_factory",
        f"    from {root}._core.hooks import tableframe_of",
        "",
        "    register_factory(pl.LazyFrame, tableframe_of)",
        "",
        "",
        "register_loader(_load_registry)",
    ]
    return "\n".join(lines) + "\n"


def _render_lazygroupby_py(syms: list[Symbol], root: str) -> str:
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        f"from {root}._core.hooks import run_hook",
        f"from {root}._core.translate import unwrap, wrap",
        "",
        "",
        "class LazyGroupBy:",
        "    def __init__(self, lgb, parent, by):",
        "        self._lgb = lgb",
        "        self._parent = parent",
        "        self._by = by  # (positional, named) group keys, for the agg hook",
        "",
    ]
    for sym in syms:
        name = _member(sym)
        if sym.hook_name == "agg":
            lines += _agg_body()
        else:
            # A LazyGroupBy result (e.g. having) re-wraps as our LazyGroupBy with the
            # same parent + keys; a LazyFrame result clones the parent; else wrap.
            lines += [
                f"    def {name}(self, *args, **kwargs):",
                f"        out = self._lgb.{name}(*unwrap(args), **unwrap(kwargs))",
                "        if isinstance(out, type(self._lgb)):",
                "            return LazyGroupBy(out, self._parent, self._by)",
                "        if isinstance(out, type(self._parent._lf)):",
                "            return self._parent._clone(out)",
                "        return wrap(out)",
                "",
            ]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# TableFrame per-op bodies.
# --------------------------------------------------------------------------- #
def _tableframe_member(sym: Symbol, root: str) -> list[str]:
    name = _member(sym)
    if sym.is_property:
        return [
            "    @property",
            f"    def {name}(self):",
            f"        return wrap(self._lf.{name})",
            "",
        ]
    if sym.hook_name == "join":
        return _join_body()
    if sym.hook_name == "project":
        return _project_body(name)
    if sym.hook_name == "group_by":
        return _group_by_body(name, root)
    if sym.hook_name == "drop":
        return _drop_body()
    if sym.hook_name == "rename":
        return _rename_body()
    # default: transparent. A LazyFrame result is a derived frame (carry hook state
    # via _clone); anything else (Schema, scalar, str, ...) is wrapped as a value.
    return [
        f"    def {name}(self, *args, **kwargs):",
        f"        out = self._lf.{name}(*unwrap(args), **unwrap(kwargs))",
        "        return self._clone(out) "
        "if isinstance(out, type(self._lf)) else wrap(out)",
        "",
    ]


def _project_body(name: str) -> list[str]:
    replace_all = "True" if name == "select" else "False"
    return [
        f"    def {name}(self, *exprs, **named_exprs):",
        "        u_args = unwrap(exprs)",
        "        u_named = unwrap(named_exprs)",
        f"        out = self._clone(self._lf.{name}(*u_args, **u_named))",
        f'        return run_hook("{name}", out, sources=(self,), '
        'params={"exprs": u_args, "named": u_named, "replace_all": '
        + replace_all
        + "})",
        "",
    ]


def _join_body() -> list[str]:
    return [
        '    def join(self, other, on=None, how="inner", *, '
        'left_on=None, right_on=None, suffix="_right"):',
        "        out = self._clone(self._lf.join(other._lf, on=unwrap(on), how=how, "
        "left_on=unwrap(left_on), right_on=unwrap(right_on), suffix=suffix))",
        '        return run_hook("join", out, sources=(self, other), '
        'params={"on": unwrap(on), '
        '"how": how, "left_on": unwrap(left_on), "right_on": unwrap(right_on), '
        '"suffix": suffix})',
        "",
    ]


def _group_by_body(name: str, root: str) -> list[str]:
    return [
        f"    def {name}(self, *by, **named_by):",
        f"        from {root}.group_by import LazyGroupBy",
        "        u_by = unwrap(by)",
        "        u_named = unwrap(named_by)",
        f"        return LazyGroupBy("
        f"self._lf.{name}(*u_by, **u_named), self, (u_by, u_named))",
        "",
    ]


def _drop_body() -> list[str]:
    return [
        "    def drop(self, *columns, **kwargs):",
        "        u_columns = unwrap(columns)",
        "        out = self._clone(self._lf.drop(*u_columns, **unwrap(kwargs)))",
        '        return run_hook("drop", out, sources=(self,), '
        'params={"columns": u_columns})',
        "",
    ]


def _rename_body() -> list[str]:
    return [
        "    def rename(self, mapping, *args, **kwargs):",
        "        u_mapping = unwrap(mapping)",
        "        out = self._clone("
        "self._lf.rename(u_mapping, *unwrap(args), **unwrap(kwargs)))",
        '        return run_hook("rename", out, sources=(self,), '
        'params={"mapping": u_mapping})',
        "",
    ]


def _agg_body() -> list[str]:
    return [
        "    def agg(self, *aggs, **named_aggs):",
        "        u_args = unwrap(aggs)",
        "        u_named = unwrap(named_aggs)",
        "        out = self._parent._clone(self._lgb.agg(*u_args, **u_named))",
        "        by, named_by = self._by",
        '        return run_hook("agg", out, sources=(self._parent,), '
        'params={"by": by, "named_by": named_by, '
        '"aggs": u_args, "named_aggs": u_named})',
        "",
    ]


# --------------------------------------------------------------------------- #
# .pyi rendering (first cut; merge/preserve comes next).
# --------------------------------------------------------------------------- #
def _render_pyi(
    syms: list[Symbol],
    previous: PyiDoc | None,
    typing_gen: TypingGen,
    module: str,
    root: str,
) -> tuple[str, set[str]]:
    body: list[str] = []
    used_our: set[str] = set()
    used_aliases: set[str] = set()
    engine_base = False
    # module docstring placeholder (preserved if the user filled it)
    body += _docstring_lines(
        _preserved(previous.module_doc if previous else None), body_indent=""
    )
    body.append("")
    if syms[0].target_class is None:
        for sym in syms:
            entry, our, aliases = _pyi_entry(
                sym, previous, typing_gen, indent="", cls_name=None
            )
            body += entry
            used_our |= our
            used_aliases |= aliases
    else:
        for cls_name, cls_syms in _group_by_class(syms).items():
            class_doc = _preserved(
                previous.class_docs.get(cls_name) if previous else None
            )
            # TableFrame subclasses EngineFrame so the engine surface (the gated
            # constructor plus _state / _lf / _ACCESS_*) resolves through the real
            # base instead of looking unbound on the stubbed class.
            if cls_name == "TableFrame":
                engine_base = True
                body += ["", f"class {cls_name}(EngineFrame):"]
            else:
                body += ["", f"class {cls_name}:"]
            body += _docstring_lines(class_doc, body_indent="    ")
            for sym in cls_syms:
                entry, our, aliases = _pyi_entry(
                    sym, previous, typing_gen, indent="    ", cls_name=cls_name
                )
                body += entry
                used_our |= our
                used_aliases |= aliases

    head = [_pyi_header(), "from __future__ import annotations", ""]
    if engine_base:
        head.append(f"from {root}._engine.frame.frame import EngineFrame")
    head += typing_gen.imports_for(used_our, used_aliases, in_module=module)
    head.append("")
    return "\n".join(head + body) + "\n", used_aliases


def _pyi_entry(
    sym: Symbol,
    previous: PyiDoc | None,
    typing_gen: TypingGen,
    *,
    indent: str,
    cls_name: str | None,
) -> tuple[list[str], set[str], set[str]]:
    name = _member(sym)
    signature, used_our, used_aliases = typing_gen.rewrite_signature(sym.signature)
    docstring: str | None = None
    lines: list[str] = []

    if previous is not None:
        existing = previous.funcs.get((cls_name, name))
        if existing is None:
            lines.append(f"{indent}{_PYI_NEW}")
        elif existing.canonical_signature != canonical_signature(signature):
            lines.append(f"{indent}{_PYI_CHANGED}")
            docstring = existing.docstring  # keep old pydoc for the human to fix
        else:
            docstring = existing.docstring  # unchanged: preserve verbatim

    if sym.is_property:
        lines.append(f"{indent}@property")
    # every entity gets a docstring placeholder to fill in (preserved if present)
    lines.append(f"{indent}def {name}{signature}:")
    lines += _docstring_lines(_preserved(docstring), indent + "    ")
    lines.append("")
    return lines, used_our, used_aliases


def _preserved(docstring: str | None) -> str:
    return docstring if docstring else " "  # empty placeholder to fill in


def _docstring_lines(docstring: str, body_indent: str) -> list[str]:
    if "\n" not in docstring:
        return [f'{body_indent}"""{docstring}"""']
    out = [f'{body_indent}"""']
    out += [f"{body_indent}{line}" if line else "" for line in docstring.split("\n")]
    out.append(f'{body_indent}"""')
    return out


# --------------------------------------------------------------------------- #
# Helpers.
# --------------------------------------------------------------------------- #
def _member(sym: Symbol) -> str:
    return sym.id.split(".", 1)[1]


def _polars_class(sym: Symbol) -> tuple[str, str]:
    class_path = sym.polars_qualname.rsplit(".", 1)[0]
    module, name = class_path.rsplit(".", 1)
    return module, name
