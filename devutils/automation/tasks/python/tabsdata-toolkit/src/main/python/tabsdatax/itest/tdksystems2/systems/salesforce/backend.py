"""Salesforce backend — a credential-only org (no container, no schema).

A domain is a clone of the org credentials (Salesforce has no per-domain entity
container). ``status`` is a lenient HTTPS reachability probe on the org URL (any
response means the host answered). Config comes from the ``SALESFORCE__``
environment (URL / USERNAME / PASSWORD / TOKEN).

The org has a data plane, but not the shared one: there is no schema to install
and its records are generated by a snowfakery recipe and bulk-uploaded, rather
than built as Tables and inserted. So a model is available here when the org
ships one under ``domain/models/<model>/`` (a recipe + a CumulusCI load mapping,
the salesforce analogue of the SQL systems' per-model DDL), and the three domain
verbs that would otherwise reach for the shared pipeline are overridden in
``domain/``. ``modify-data`` stays off — a load is a full wipe and replace.
"""

from __future__ import annotations

import urllib.error
import urllib.request
from pathlib import Path

from tabsdatax.itest.tdksystems2 import _venv
from tabsdatax.itest.tdksystems2.systems._common.service import ServiceBackend

RECIPE_SUFFIX = ".recipe.yml"


class Salesforce(ServiceBackend):
    # The org's data plane is snowfakery + cumulusci, which cannot share an env
    # with the SQL drivers (sqlalchemy<2 vs >=2).
    dom_env = _venv.ENV_B

    supports_models = True
    supports_data = True

    slug = "salesforce"
    label = "Salesforce"
    kind = "salesforce"
    domain_word = "org"
    env_prefix = "SALESFORCE"
    cred_keys = ("URL", "USERNAME", "PASSWORD", "TOKEN")
    public_creds = frozenset({"URL", "USERNAME"})

    def models_root(self) -> Path:
        return Path(__file__).resolve().parent / "domain" / "models"

    def model_assets(self, model: str) -> Path:
        """The org's directory for `model` — its snowfakery recipe and CumulusCI
        load mapping."""
        return self.models_root() / model

    def has_model(self, model: str) -> bool:
        return any(self.model_assets(model).glob(f"*{RECIPE_SUFFIX}"))

    def available_models(self) -> list[str]:
        root = self.models_root()
        if not root.is_dir():
            return []
        return sorted(d.name for d in root.iterdir() if self.has_model(d.name))

    @staticmethod
    def _reachable(url: str) -> bool:
        if not url:
            return False
        try:
            urllib.request.urlopen(url, timeout=10)  # noqa: S310
            return True
        except urllib.error.HTTPError:
            return True  # the host answered (even a 4xx) — it's reachable
        except Exception:  # noqa: BLE001 - connection/DNS failure = unreachable
            return False

    def _status(self, meta: dict[str, str], what: str) -> tuple[bool, str]:
        ok, detail = self._creds_present(meta, what)
        if not ok:
            return ok, detail
        url = meta.get("URL", "")
        reachable = self._reachable(url)
        return reachable, f"{what}: {url} {'reachable' if reachable else 'unreachable'}"

    def system_status(self, meta: dict[str, str]) -> tuple[bool, str]:
        return self._status(meta, f"{self.label} org")

    def domain_status(self, domain_meta: dict[str, str]) -> tuple[bool, str]:
        return self._status(domain_meta, f"{self.label} domain")
