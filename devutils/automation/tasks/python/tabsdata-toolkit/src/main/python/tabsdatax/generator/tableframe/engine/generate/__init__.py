# Return types that yield a derived frame (route through compute).
_FRAME_RETURNS = frozenset({"LazyFrame"})
# Return types wrappable into one of our value wrappers (wrap()).
_WRAP_RETURNS = frozenset({
    "DataFrame",
    "Schema",
    "LazyGroupBy",
    "tuple[DataFrame, DataFrame]",
    "Iterator[DataFrame]",
})
# Scalar / stdlib return types returned as-is (wrap passes them through anyway).
_PASSTHROUGH_RETURNS = frozenset({
    "int",
    "str",
    "bool",
    "bytes",
    "list[str]",
    "list[DataType]",
    "T",
})


def _normalize_return(returns: str) -> str:
    text = returns.strip()
    for prefix in ("pl.", "pc."):
        if text.startswith(prefix):
            text = text[len(prefix) :]
    if text.endswith(" | None"):
        text = text[: -len(" | None")]
    return text.strip()


def _body_kind(symbol: Symbol) -> str:
    """Classify a symbol's op body by its manifest return type: route a frame
    result through ``compute``, ``wrap`` a wrappable polars object, return a
    scalar as-is, or ``raise`` for unsupported / unmodeled returns."""
    returns = _normalize_return(symbol.returns)
    if returns in _FRAME_RETURNS:
        return "compute"
    if returns in _WRAP_RETURNS:
        return "wrap"
    if returns in _PASSTHROUGH_RETURNS:
        return "passthrough"
    return "raise"


_HOOKED_BODIES = {
    "join": lambda name, root: _join_body(),
    "project": lambda name, root: _project_body(name),
    "group_by": lambda name, root: _group_by_body(name, root),
    "drop": lambda name, root: _drop_body(),
    "rename": lambda name, root: _rename_body(),
}

# Frame methods with a custom generated body (keyed by member name, not
# hook_name, so they need no manifest hook; each still routes through compute()).
# sort forces a perf default (signature preserved); unique / __getitem__ are
# system-column-aware so their user-visible result matches polars.
_CUSTOM_BODIES = {
    "sort": lambda name, root: _sort_body(),
    "unique": lambda name, root: _unique_body(),
    "__getitem__": lambda name, root: _getitem_body(),
}


def _tableframe_member(symbol: Symbol, root: str) -> list[str]:
    name = _member(symbol)
    if symbol.is_property:
        return [
            "    @property",
            f"    def {name}(self):",
            f"        return wrap(self._lf.{name})",
            "",
        ]
    hooked = _HOOKED_BODIES.get(symbol.hook_name)
    if hooked is not None:
        return hooked(name, root)
    custom = _CUSTOM_BODIES.get(name)
    if custom is not None:
        return custom(name, root)
    return _classified_body(_body_kind(symbol), name, root)


def _classified_body(kind: str, name: str, root: str) -> list[str]:
    if kind == "compute":
        return [
            f"    def {name}(self, *args, **kwargs):",
            "        u_args = unwrap(args)",
            "        u_kwargs = unwrap(kwargs)",
            f'        return compute("{name}", (self,), {{}},',
            f"            call=lambda lf: lf.{name}(*u_args, **u_kwargs))",
            "",
        ]
    if kind == "wrap":
        return [
            f"    def {name}(self, *args, **kwargs):",
            f"        return wrap(self._lf.{name}(*unwrap(args), **unwrap(kwargs)))",
            "",
        ]
    if kind == "passthrough":
        return [
            f"    def {name}(self, *args, **kwargs):",
            f"        return self._lf.{name}(*unwrap(args), **unwrap(kwargs))",
            "",
        ]
    return [
        f"    def {name}(self, *args, **kwargs):",
        f"        from {root}._engine.event.error import TableFrameErrorCode",
        "",
        f'        raise TableFrameErrorCode.TF5.exception(op="{name}")',
        "",
    ]


def _project_body(name: str) -> list[str]:
    replace_all = "True" if name == "select" else "False"
    return [
        f"    def {name}(self, *exprs, **named_exprs):",
        "        u_args = unwrap(exprs)",
        "        u_named = unwrap(named_exprs)",
        f'        return compute("{name}", (self,), '
        '{"exprs": u_args, "named": u_named, "replace_all": ' + replace_all + "},",
        f"            call=lambda lf: lf.{name}(*u_args, **u_named))",
        "",
    ]


def _join_body() -> list[str]:
    # Forced kwargs (validate/allow_parallel/force_parallel) match the legacy
    # TableFrame join contract; they are not user-tunable.
    return [
        '    def join(self, other, on=None, how="inner", *, '
        'left_on=None, right_on=None, suffix="_right"):',
        "        u_on = unwrap(on)",
        "        u_left_on = unwrap(left_on)",
        "        u_right_on = unwrap(right_on)",
        '        return compute("join", (self, other), '
        '{"on": u_on, "how": how, "left_on": u_left_on, '
        '"right_on": u_right_on, "suffix": suffix},',
        "            call=lambda left, right: left.join(right, on=u_on, how=how, "
        "left_on=u_left_on, right_on=u_right_on, suffix=suffix, "
        'validate="m:m", allow_parallel=True, force_parallel=False))',
        "",
    ]


def _group_by_body(name: str, root: str) -> list[str]:
    return [
        f"    def {name}(self, *by, **named_by):",
        f"        from {root}.group_by import LazyGroupBy",
        "        u_by = unwrap(by)",
        "        u_named = unwrap(named_by)",
        f"        return LazyGroupBy("
        f"self._lf.{name}(*u_by, **u_named), self, (u_by, u_named))",
        "",
    ]


def _drop_body() -> list[str]:
    return [
        "    def drop(self, *columns, **kwargs):",
        "        u_columns = unwrap(columns)",
        "        u_kwargs = unwrap(kwargs)",
        '        return compute("drop", (self,), {"columns": u_columns},',
        "            call=lambda lf: lf.drop(*u_columns, **u_kwargs))",
        "",
    ]


def _rename_body() -> list[str]:
    # A callable mapping applies to USER columns only, so system columns are never
    # renamed; it is expanded to a dict before the op (which also lets the
    # system-column guard see the concrete targets).
    return [
        "    def rename(self, mapping, *args, **kwargs):",
        "        u_mapping = unwrap(mapping)",
        "        if callable(u_mapping):",
        "            u_mapping = {name: u_mapping(name) "
        "for name in self._user_columns()}",
        "        u_args = unwrap(args)",
        "        u_kwargs = unwrap(kwargs)",
        '        return compute("rename", (self,), {"mapping": u_mapping},',
        "            call=lambda lf: lf.rename(u_mapping, *u_args, **u_kwargs))",
        "",
    ]


def _sort_body() -> list[str]:
    # multithreaded defaults to False for deterministic ordering, but the polars
    # signature is preserved: a caller may override it.
    return [
        "    def sort(self, *args, **kwargs):",
        "        u_args = unwrap(args)",
        "        u_kwargs = unwrap(kwargs)",
        '        u_kwargs.setdefault("multithreaded", False)',
        '        return compute("sort", (self,), {},',
        "            call=lambda lf: lf.sort(*u_args, **u_kwargs))",
        "",
    ]


def _unique_body() -> list[str]:
    # With no subset, dedup over USER columns only: system columns ($td.id is
    # per-row unique) would otherwise defeat the dedup entirely.
    return [
        "    def unique(self, subset=None, **kwargs):",
        "        u_subset = unwrap(subset)",
        "        if u_subset is None:",
        "            u_subset = self._user_columns()",
        "        u_kwargs = unwrap(kwargs)",
        '        return compute("unique", (self,), {},',
        "            call=lambda lf: lf.unique(u_subset, **u_kwargs))",
        "",
    ]


def _getitem_body() -> list[str]:
    # A list/str of column names selects columns (routed through select(), which
    # reassembles system columns); int/range/slice is row indexing.
    return [
        "    def __getitem__(self, item):",
        "        u_item = unwrap(item)",
        "        if isinstance(u_item, str):",
        "            return self.select(u_item)",
        "        if isinstance(u_item, list) and all("
        "isinstance(name, str) for name in u_item):",
        "            return self.select(*u_item)",
        "        return compute("
        '"__getitem__", (self,), {}, call=lambda lf: lf.__getitem__(u_item))',
        "",
    ]


def _agg_body() -> list[str]:
    # agg's call closes over self._lgb (the grouper), not a lazyframe input, so it
    # ignores the lazyframes compute passes; sources / build use the parent frame.
    return [
        "    def agg(self, *aggs, **named_aggs):",
        "        u_args = unwrap(aggs)",
        "        u_named = unwrap(named_aggs)",
        "        by, named_by = self._by",
        '        return compute("agg", (self._parent,), '
        '{"by": by, "named_by": named_by, '
        '"aggs": u_args, "named_aggs": u_named},',
        "            call=lambda *_: self._lgb.agg(*u_args, **u_named))",
        "",
    ]


# --------------------------------------------------------------------------- #
# .pyi rendering (first cut; merge/preserve comes next).
# --------------------------------------------------------------------------- #
def _render_pyi(
    symbols: list[Symbol],
    previous: PyiDoc | None,
    annotation_rewriter: AnnotationRewriter,
    module: str,
    root: str,
) -> tuple[str, set[str]]:
    body: list[str] = []
    used_our: set[str] = set()
    used_aliases: set[str] = set()
    engine_base = False
    # The module docstring placeholder is preserved if the user filled it.
    module_doc = previous.module_doc if previous is not None else None
    body += _docstring_lines(_preserved(module_doc), body_indent="")
    body.append("")
    if symbols[0].target_class is None:
        for symbol in symbols:
            entry, our, aliases = _pyi_entry(
                symbol, previous, annotation_rewriter, indent="", class_name=None
            )
            body += entry
            used_our |= our
            used_aliases |= aliases
    else:
        for class_name, class_symbols in _group_by_class(symbols).items():
            class_doc = _preserved(
                previous.class_docs.get(class_name) if previous else None
            )
            # TableFrame subclasses EngineFrame so the engine API (the gated
            # constructor plus _state / _lf / _ACCESS_*) resolves through the real
            # base instead of looking unbound on the stubbed class.
            if class_name == "TableFrame":
                engine_base = True
                body += ["", f"class {class_name}(EngineFrame):"]
            else:
                body += ["", f"class {class_name}:"]
            body += _docstring_lines(class_doc, body_indent="    ")
            constructor_parameters = _SCAFFOLD_CONSTRUCTORS.get(class_name)
            if constructor_parameters is not None:
                signature = f"(self, {', '.join(constructor_parameters)}) -> None"
                body += _pyi_def(
                    "__init__",
                    signature,
                    previous,
                    indent="    ",
                    class_name=class_name,
                )
            for symbol in class_symbols:
                entry, our, aliases = _pyi_entry(
                    symbol,
                    previous,
                    annotation_rewriter,
                    indent="    ",
                    class_name=class_name,
                )
                body += entry
                used_our |= our
                used_aliases |= aliases

    head = [_pyi_header(), "from __future__ import annotations", ""]
    if engine_base:
        head.append(f"from {root}._engine.frame.frame import EngineFrame")
    head += annotation_rewriter.imports_for(used_our, used_aliases, in_module=module)
    head.append("")
    return "\n".join(head + body) + "\n", used_aliases


def _pyi_entry(
    symbol: Symbol,
    previous: PyiDoc | None,
    annotation_rewriter: AnnotationRewriter,
    *,
    indent: str,
    class_name: str | None,
) -> tuple[list[str], set[str], set[str]]:
    name = _member(symbol)
    source_signature = _SIGNATURE_OVERRIDES.get(symbol.id, symbol.signature)
    signature, used_our, used_aliases = annotation_rewriter.rewrite_signature(
        source_signature
    )
    lines = _pyi_def(
        name,
        signature,
        previous,
        is_property=symbol.is_property,
        indent=indent,
        class_name=class_name,
    )
    return lines, used_our, used_aliases


def _pyi_def(
    name: str,
    signature: str,
    previous: PyiDoc | None,
    *,
    is_property: bool = False,
    indent: str,
    class_name: str | None,
) -> list[str]:
    docstring: str | None = None
    lines: list[str] = []

    if previous is not None:
        existing = previous.functions.get((class_name, name))
        if existing is None:
            lines.append(f"{indent}{_PYI_NEW}")
        elif existing.canonical_signature != canonical_signature(signature):
            lines.append(f"{indent}{_PYI_CHANGED}")
            docstring = existing.docstring  # keep old pydoc for the human to fix
        else:
            docstring = existing.docstring  # unchanged: preserve verbatim

    if is_property:
        lines.append(f"{indent}@property")
    # Every entity gets a docstring placeholder to fill in (preserved if present).
    lines.append(f"{indent}def {name}{signature}:")
    lines += _docstring_lines(_preserved(docstring), indent + "    ")
    lines.append("")
    return lines


def _preserved(docstring: str | None) -> str:
    return docstring if docstring else " "  # empty placeholder to fill in


def _docstring_lines(docstring: str, body_indent: str) -> list[str]:
    if "\n" not in docstring:
        return [f'{body_indent}"""{docstring}"""']
    out = [f'{body_indent}"""']
    out += [f"{body_indent}{line}" if line else "" for line in docstring.split("\n")]
    out.append(f'{body_indent}"""')
    return out


