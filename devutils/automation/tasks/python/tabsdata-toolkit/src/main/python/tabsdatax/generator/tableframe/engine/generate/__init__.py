_PYI_CHANGED = "# Signature changed; validate and fix the docstring below."
_PYI_NEW = "# New signature; write the docstring below."


def _copyright() -> str:
    return f"# Copyright {datetime.date.today().year} Tabsdata Inc."


def _py_header() -> str:
    return f"{_copyright()}\n# GENERATED by tdx-gtableframe — do not edit by hand.\n"


def _pyi_header() -> str:
    return (
        f"{_copyright()}\n"
        "# GENERATED by tdx-gtableframe — stubs; add/maintain docstrings here.\n"
    )


def _test_header() -> str:
    return (
        f"{_copyright()}\n"
        "# GENERATED by tdx-gtableframe — overwritten on regen; "
        "put custom tests in other files.\n"
    )


# Each dispatching hook_name -> (number of source frames, ordered (field, type) of
# the params dict the op passes). Drives both the generated op bodies' contract and
# the per-op hook types emitted into _core/hooks.py. group_by builds a grouper (its
# hook fires at agg time), so it isn't here.
_HOOK_SHAPES: dict[str, tuple[int, list[tuple[str, str]]]] = {
    "project": (1, [("exprs", "tuple"), ("named", "dict"), ("replace_all", "bool")]),
    "join": (
        2,
        [
            ("on", "Any"),
            ("how", "str"),
            ("left_on", "Any"),
            ("right_on", "Any"),
            ("suffix", "str"),
        ],
    ),
    "drop": (1, [("columns", "tuple")]),
    "rename": (1, [("mapping", "Any")]),
    "agg": (
        1,
        [
            ("by", "tuple"),
            ("named_by", "dict"),
            ("aggs", "tuple"),
            ("named_aggs", "dict"),
        ],
    ),
}
_HOOK_NAMES = set(_HOOK_SHAPES)

# Constructors of generator-scaffolded classes (class name -> parameter names).
# These have no manifest symbol — the runtime renderers emit them as
# scaffolding — so the .pyi renderer sources them from here; otherwise the stub
# class has no __init__ and type checkers fall back to ``object()``'s
# zero-argument constructor, flagging every construction site.
_SCAFFOLD_CONSTRUCTORS: dict[str, tuple[str, ...]] = {
    "LazyGroupBy": ("lgb", "parent", "by"),
}


@dataclass
class GenResult:
    modules: list[str] = field(default_factory=list)
    symbol_count: int = 0
    deferred: dict[str, int] = field(default_factory=dict)
    # Module -> symbols that were in the previous .pyi but are no longer emitted.
    dropped: dict[str, list[str]] = field(default_factory=dict)
    # Generated test files (overwritten on regeneration).
    tests: list[str] = field(default_factory=list)


def _build_type_registry(
    whitelisted: list, datatypes: list[str], module: str
) -> tuple[set[str], dict[str, str]]:
    """Map every name kept verbatim in .pyi annotations to the module it is
    imported from: wrapper classes, TableFrame, the datatype aliases, and the
    public table specs used by hand-typed stubs (see _SIGNATURE_OVERRIDES)."""
    class_module: dict[str, str] = {}
    for symbol in whitelisted:
        if symbol.target_class is not None:
            class_module[symbol.target_class] = symbol.target_module
    our_types = set(class_module) | {"TableFrame"} | set(datatypes)
    class_module["TableFrame"] = module
    for datatype in datatypes:
        class_module[datatype] = f"{module}.datatypes"
    for spec in _API_SPEC_TYPES:
        our_types.add(spec)
        class_module[spec] = _API_MODULE
    return our_types, class_module


def perform(
    report: Report, module: str, main_root: str, test_root: str | None = None
) -> GenResult:
    base = Path(main_root).joinpath(*module.split("."))
    by_module: dict[str, list[Symbol]] = defaultdict(list)
    result = GenResult()

    whitelisted = [symbol for symbol in report.symbols if symbol.whitelisted]
    for symbol in whitelisted:
        by_module[symbol.target_module].append(symbol)

    # Hookable op names are the method names of hook-dispatching ops (across
    # modules, e.g. agg is a LazyGroupBy method). Used for _HOOKABLE_OPS.
    hookable = sorted({
        _member(symbol) for symbol in whitelisted if symbol.hook_name in _HOOK_NAMES
    })
    hook_specs = sorted({
        (_member(symbol), symbol.hook_name)
        for symbol in whitelisted
        if symbol.hook_name in _HOOK_NAMES
    })

    # The datatypes.py module is always emitted (aliased leaf types); it is not a
    # manifest module but must be a submodule so the __init__ loop imports it
    # (registering the passthrough types).
    datatypes = datatype_names()
    submodules = sorted(
        {
            module_name[len(module) + 1 :]
            for module_name in by_module
            if module_name != module
        }
        | {"datatypes"}
    )

    # No polars/numpy type names leak into the .pyi stubs: rewrite annotations and
    # redefine the polars type aliases we use into <root>._typing. The datatype
    # names are ours too (aliased in datatypes.py), so keep + import them from there.
    our_types, class_module = _build_type_registry(whitelisted, datatypes, module)
    annotation_rewriter = AnnotationRewriter(our_types, class_module, module)
    all_aliases: set[str] = set()

    written: list[Path] = []
    base.mkdir(parents=True, exist_ok=True)
    written += _write_core(base, module, _render_hook_types(hook_specs))
    written.append(_write_datatypes(base, module, datatypes))
    for module_name, symbols in sorted(by_module.items()):
        is_root = module_name == module
        filename = "__init__" if is_root else module_name[len(module) + 1 :]
        py_path = base / f"{filename}.py"
        py_path.write_text(_render_py(symbols, module, is_root, hookable, submodules))
        written.append(py_path)

        # Regenerate the .pyi, preserving handwritten docstrings: rename any
        # existing stub to a transient .pyi-ori, read it, then drop it.
        pyi_path = base / f"{filename}.pyi"
        previous: PyiDoc | None = None
        if pyi_path.exists():
            ori_path = base / f"{filename}.pyi-ori"
            pyi_path.replace(ori_path)
            try:
                previous = parse_pyi(ori_path.read_text())
            except SyntaxError:
                previous = None  # a corrupt prior stub shouldn't block regeneration
            finally:
                ori_path.unlink()
        text, aliases = _render_pyi(
            symbols, previous, annotation_rewriter, module_name, module
        )
        pyi_path.write_text(text)
        written.append(pyi_path)
        all_aliases |= aliases
        if previous is not None:
            current = {(symbol.target_class, _member(symbol)) for symbol in symbols}
            dropped = sorted(name for (_, name) in set(previous.functions) - current)
            if dropped:
                # noinspection PyTypeChecker
                result.dropped[module_name] = dropped

        result.modules.append(module_name)
        result.symbol_count += len(symbols)

    typing_pyi = base / "_typing.pyi"
    typing_pyi.write_text(
        _pyi_header() + "\n" + annotation_rewriter.render_typing_pyi(all_aliases)
    )
    written.append(typing_pyi)

    # Tests are always generated; the folder is derived from main_root if not given.
    test_root = test_root or _default_test_root(main_root, module)
    result.tests, test_files = _generate_tests(by_module, module, test_root)
    written += test_files

    _format(written)
    return result


_CORE_MODULES = ("base", "translate", "hooks")


def _write_core(base: Path, module: str, hook_types: str) -> list[Path]:
    """Emit the _core runtime (base/translate/hooks) from bundled templates.

    These are the framework runtime, not customization — customization lives in
    registered hooks. Regenerated each run with the root module substituted in;
    hooks.py also gets the per-op hook types (``__HOOK_TYPES__`` placeholder).
    """
    core_dir = base / "_core"
    core_dir.mkdir(parents=True, exist_ok=True)
    templates = Path(__file__).parent / "templates"
    written = []
    for name in _CORE_MODULES:
        text = (
            (templates / f"{name}.py.tmpl")
            .read_text()
            .replace("__ROOT_MODULE__", module)
            .replace("__HOOK_TYPES__", hook_types)
        )
        path = core_dir / f"{name}.py"
        path.write_text(_py_header() + "\n" + text)
        written.append(path)
    return written


def _pascal(name: str) -> str:
    return "".join(word.capitalize() for word in name.split("_"))


def _render_hook_types(specs: list[tuple[str, str]]) -> str:
    """Render the per-op params types for hooks.py: one ``<HookName>Params``
    TypedDict per distinct hook_name, documenting exactly what a routed op passes
    to its hooks in the ``params`` dict.

    ``specs`` is (op-name, hook_name) per hookable op — e.g. ("with_columns",
    "project"), ("join", "join"). Empty input yields an empty block.
    """
    if not specs:
        return ""
    lines: list[str] = []
    for hook_name in sorted({hook_name for _, hook_name in specs}):
        _, fields = _HOOK_SHAPES[hook_name]
        lines += [
            f"class {_pascal(hook_name)}Params(TypedDict):",
            f'    """Params a {hook_name!r} op passes to its hooks."""',
            "",
        ]
        lines += [f"    {field_name}: {type_text}" for field_name, type_text in fields]
        lines += ["", ""]
    return "\n".join(lines).rstrip("\n")


def _write_datatypes(base: Path, module: str, names: list[str]) -> Path:
    """Emit datatypes.py: alias the public polars datatypes as ours, register
    DataType as a passthrough leaf type (wrap() returns them unchanged), and an
    editable ``_ALLOWED_TYPES`` allow-list enforced via ``_valid_type``."""
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "",
        f"from {module}._core.translate import "
        "register_passthrough, register_type_validator",
        "",
    ]
    for name in names:
        lines.append(f"{name} = pl.{name}")
    lines += [
        "",
        "",
        "# The datatypes this API accepts. Defaults to every alias above; remove",
        "# entries to restrict the allowed set. Enforced on datatype arguments and",
        "# on the schema of any LazyFrame entering a TableFrame.",
        "_ALLOWED_TYPES = [",
    ]
    lines += [f"    {name}," for name in names]
    lines += [
        "]",
        "",
        "",
        "def _valid_type(dtype):",
        '    """Assert `dtype` (possibly nested/parametrized) uses only allowed types;',
        '    return it. Raises TypeError on the first disallowed type."""',
        "    base = dtype if isinstance(dtype, type) else type(dtype)",
        "    if base not in _ALLOWED_TYPES:",
        "        raise TypeError(",
        '            f"tableframe: datatype {base.__name__!r} is not allowed "',
        '            f"(see _ALLOWED_TYPES in {__name__})"',
        "        )",
        '    inner = getattr(dtype, "inner", None)  # List / Array element type',
        "    if inner is not None:",
        "        _valid_type(inner)",
        '    for field in getattr(dtype, "fields", None) or ():  # Struct fields',
        "        _valid_type(field.dtype)",
        "    return dtype",
        "",
        "",
        "# Datatypes are aliased leaf types: wrap() returns any DataType unchanged,",
        "# and _valid_type enforces the allow-list wherever a type is set.",
        "register_passthrough(pl.DataType)",
        "register_type_validator(_valid_type)",
    ]
    path = base / "datatypes.py"
    path.write_text("\n".join(lines) + "\n")
    return path


def _default_test_root(main_root: str, module: str) -> str:
    parts = list(Path(main_root).parts)
    if "main" in parts:  # Maven layout: src/main/python -> src/utest/python
        parts[parts.index("main")] = "utest"
    first, *rest = module.split(".")
    return str(Path(*parts).joinpath(f"test_{first}", *rest, "generator"))


def _format(paths: list[Path]) -> None:
    config = str(Path(__file__).parent / "ruff.toml")
    sources = [str(path) for path in paths]
    # .pyi stubs are formatted but NOT lint-fixed: `ruff check --fix` would strip
    # imports it reads as unused (a stub's names are used only in annotations),
    # breaking the stub. `.py` files get both passes (matches cargo make format_py).
    code = [str(path) for path in paths if path.suffix != ".pyi"]
    commands = [
        [sys.executable, "-m", "ruff", "format", "--config", config, *sources],
    ]
    if code:
        commands.append([
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--fix",
            "--config",
            config,
            *code,
        ])
    for command in commands:
        try:
            subprocess.run(command, check=True, capture_output=True)
        except (FileNotFoundError, subprocess.CalledProcessError):
            pass  # ruff not installed, or a file it couldn't fix — leave as-is


