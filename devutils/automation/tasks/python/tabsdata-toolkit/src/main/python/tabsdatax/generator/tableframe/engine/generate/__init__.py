def _render_py(
    symbols: list[Symbol],
    root: str,
    is_root: bool,
    hookable: list[str],
    submodules: list[str],
) -> str:
    target_class = symbols[0].target_class
    if target_class is None:
        return _render_functions_py(symbols, root)
    if is_root:
        return _render_tableframe_py(symbols, root, hookable, submodules)
    if target_class == "LazyGroupBy":
        return _render_lazygroupby_py(symbols, root)
    return _render_value_class_py(symbols, root)


def _render_functions_py(symbols: list[Symbol], root: str) -> str:
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "",
        f"from {root}._core.translate import unwrap, wrap",
        "",
    ]
    for symbol in symbols:
        name = _member(symbol)
        if name == "concat":
            lines += _concat_function_lines()
            continue
        lines += [
            "",
            f"def {name}(*args, **kwargs):",
            f"    return wrap(pl.{name}(*unwrap(args), **unwrap(kwargs)))",
        ]
    return "\n".join(lines) + "\n"


_CONCAT_METHODS = (
    "vertical",
    "vertical_relaxed",
    "diagonal",
    "diagonal_relaxed",
)

# Public table specs used in hand-typed stubs (kept verbatim by the annotation
# rewriter and imported from tabsdatak.api).
_API_MODULE = "tabsdatak.api"
_API_SPEC_TYPES = ("TableFrameSpec", "TableFramesSpec")

# .pyi signature overrides keyed by symbol id, for stubs whose public type is
# ours rather than the polars signature the manifest records. concat takes the
# TableFrame None/empty contract, so it is typed with our table specs.
_SIGNATURE_OVERRIDES = {
    "functions.concat": (
        "(items: TableFramesSpec, *, how: ConcatMethod = 'vertical') -> TableFrameSpec"
    ),
}


def _concat_function_lines() -> list[str]:
    # concat follows the TableFrame None/empty contract, which pl.concat does not:
    # concat(None) and concat of an all-None/empty iterable return None, None
    # entries within the iterable are skipped, and `how` is validated up front. A
    # throwaway concat of empty frames first surfaces schema mismatches clearly.
    methods = ", ".join(repr(method) for method in _CONCAT_METHODS)
    return [
        "",
        f"_CONCAT_METHODS = ({methods},)",
        "",
        "",
        'def concat(items=None, how="vertical"):',
        "    if items is None:",
        "        return None",
        "    if how not in _CONCAT_METHODS:",
        "        raise ValueError(",
        '            f"Invalid concatenation method: {how!r}. "',
        '            f"Expected one of {_CONCAT_METHODS}."',
        "        )",
        "    kept = [unwrap(item) for item in items if item is not None]",
        "    if not kept:",
        "        return None",
        "    empties = [",
        "        pl.DataFrame(schema=lf.collect_schema()) for lf in kept",
        "    ]",
        "    pl.concat(empties, how=how, rechunk=False, parallel=True)",
        "    return wrap(pl.concat(kept, how=how, rechunk=False, parallel=True))",
    ]


def _render_value_class_py(symbols: list[Symbol], root: str) -> str:
    # A module may hold several classes, e.g. whenthen.
    groups = _group_by_class(symbols)
    lines = [_py_header(), "from __future__ import annotations", ""]
    for class_symbols in groups.values():
        polars_module, polars_class = _polars_class(class_symbols[0])
        lines.append(f"from {polars_module} import {polars_class} as _Pl{polars_class}")
    lines += [
        f"from {root}._core.base import BaseWrapper",
        f"from {root}._core.translate import register, unwrap, wrap",
    ]
    for class_name, class_symbols in groups.items():
        _, polars_class = _polars_class(class_symbols[0])
        lines += [
            "",
            "",
            f"@register(_Pl{polars_class})",
            f"class {class_name}(BaseWrapper):",
        ]
        for symbol in class_symbols:
            name = _member(symbol)
            if symbol.is_property:
                lines += [
                    "    @property",
                    f"    def {name}(self):",
                    f"        return wrap(self._inner.{name})",
                    "",
                ]
            else:
                lines += [
                    f"    def {name}(self, *args, **kwargs):",
                    f"        return wrap("
                    f"self._inner.{name}(*unwrap(args), **unwrap(kwargs)))",
                    "",
                ]
    return "\n".join(lines) + "\n"


def _group_by_class(symbols: list[Symbol]) -> "dict[str, list[Symbol]]":
    groups: dict[str, list[Symbol]] = {}
    for symbol in symbols:
        target_class = symbol.target_class
        if target_class is None:
            continue
        groups.setdefault(target_class, []).append(symbol)
    return groups


def _render_tableframe_py(
    symbols: list[Symbol], root: str, hookable: list[str], submodules: list[str]
) -> str:
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        f"from {root}._core.hooks import compute",
        f"from {root}._core.translate import register_loader, unwrap, wrap",
        f"from {root}._engine.frame.frame import EngineFrame",
        "",
        "",
        "class TableFrame(EngineFrame):",
    ]
    # The from_* / empty / to_* construction and materialization API is
    # handwritten on EngineFrame (not generated); TableFrame inherits it, and the
    # stub's `class TableFrame(EngineFrame)` link lets tooling resolve it from source.
    for symbol in symbols:
        lines += _tableframe_member(symbol, root)

    # Lazy registry population. Importing this package must NOT drag in polars
    # (a heavy import); so the registry-filling loop — importing every submodule
    # for its @register side effects, then mapping LazyFrame -> TableFrame so
    # frame-returning ops never leak a raw pl.LazyFrame — is deferred into
    # _load_registry(), which translate calls on first actual use (first wrap miss
    # / first frame construction). At import, we only register the loader (cheap).
    lines += [
        "",
        "",
        "def _load_registry() -> None:",
        "    import importlib",
        "    import polars as pl",
        "",
        f"    for submodule in {tuple(submodules)!r}:",
        '        importlib.import_module(f"{__name__}.{submodule}")',
        "",
        "    from tabsdatak.extensions.tableframe._engine.features import install",
        "",
        "    install(TableFrame)",
        "",
        f"    from {root}._core.translate import register_factory",
        f"    from {root}._core.hooks import tableframe_of",
        "",
        "    register_factory(pl.LazyFrame, tableframe_of)",
        "",
        "",
        "register_loader(_load_registry)",
    ]
    return "\n".join(lines) + "\n"


# Group-by reductions that reduce column VALUES: they must run over user columns
# only, excluding system columns (a string $td.* would break a numeric reducer,
# and $td.id is per-row so it corrupts the grouping). len/count are excluded --
# they count rows, not values.
_GROUPBY_REDUCTIONS = frozenset(
    {"sum", "min", "max", "mean", "median", "first", "last", "n_unique", "quantile"}
)


def _groupby_reduction_body(name: str) -> list[str]:
    return [
        f"    def {name}(self, *args, **kwargs):",
        "        u_args = unwrap(args)",
        "        u_kwargs = unwrap(kwargs)",
        "        excluded = _system_columns(self._parent)",
        f'        return compute("{name}", (self._parent,), {{}},',
        "            call=lambda *_: self._lgb.agg("
        f"pl.all().exclude(excluded).{name}(*u_args, **u_kwargs)))",
        "",
    ]


def _system_columns_helper(root: str) -> list[str]:
    return [
        "def _system_columns(frame):",
        "    from tabsdatak.extensions.tableframe._engine.column.registry import (",
        "        registry,",
        "    )",
        f"    from {root}._engine.taxonomy.column import ColumnKind",
        "",
        "    names = frame._lf.collect_schema().names()",
        "    reg = registry()",
        "    return [n for n in names if reg.kind_of(n) is not ColumnKind.USER]",
        "",
        "",
    ]


def _render_lazygroupby_py(symbols: list[Symbol], root: str) -> str:
    lines = [
        _py_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "",
        f"from {root}._core.hooks import compute",
        f"from {root}._core.translate import unwrap, wrap",
        "",
        "",
        *_system_columns_helper(root),
        "class LazyGroupBy:",
        "    # agg-family ops carry lineage / provenance via after / state hooks",
        "    # over the parent; the grouper already captured the plan, so a before",
        "    # hook is inert for them (its rewritten lazyframes are not run).",
        f"    def __init__(self, {', '.join(_SCAFFOLD_CONSTRUCTORS['LazyGroupBy'])}):",
        "        self._lgb = lgb",
        "        self._parent = parent",
        "        self._by = by  # (positional, named) group keys, for the agg hook",
        "",
    ]
    for symbol in symbols:
        name = _member(symbol)
        if symbol.hook_name == "agg":
            lines += _agg_body()
        elif name in _GROUPBY_REDUCTIONS:
            lines += _groupby_reduction_body(name)
        elif _body_kind(symbol) == "compute":
            # An aggregation over the group (len/count/max/...) terminates into a
            # frame; route it through compute over the parent, like agg.
            lines += [
                f"    def {name}(self, *args, **kwargs):",
                "        u_args = unwrap(args)",
                "        u_kwargs = unwrap(kwargs)",
                f'        return compute("{name}", (self._parent,), {{}},',
                f"            call=lambda *_: self._lgb.{name}(*u_args, **u_kwargs))",
                "",
            ]
        else:
            # A LazyGroupBy result (e.g. having) re-wraps as our LazyGroupBy with the
            # same parent + keys; anything else is wrapped as a value.
            lines += [
                f"    def {name}(self, *args, **kwargs):",
                f"        out = self._lgb.{name}(*unwrap(args), **unwrap(kwargs))",
                "        if isinstance(out, type(self._lgb)):",
                "            return LazyGroupBy(out, self._parent, self._by)",
                "        return wrap(out)",
                "",
            ]
    return "\n".join(lines) + "\n"


