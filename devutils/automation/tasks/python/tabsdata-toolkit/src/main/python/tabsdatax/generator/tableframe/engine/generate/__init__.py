# Test generation — mock-spy that each wrapper call reaches polars.
# --------------------------------------------------------------------------- #
def _write_test_namespace_inits(base: Path) -> list[Path]:
    template = Path(__file__).parent / "templates" / "namespace_init.py.tmpl"
    copyright_text = _copyright().removeprefix("# ")
    text = template.read_text().replace("__COPYRIGHT__", copyright_text)
    parts = base.parts
    # Namespace inits belong only to the importable test package, i.e. the
    # folders below the source root (the `.../src/utest/python` segment). Start
    # at the LAST "python" segment, not the first — a main root like
    # `./python/tabsdata-api/src/main/python` has two, and anchoring on the
    # first would scaffold spurious inits into the non-package layout folders
    # (tabsdata-api/, src/, src/utest/).
    last_python = len(parts) - 1 - parts[::-1].index("python")
    root = last_python + 1
    written: list[Path] = []
    folder = Path(*parts[:root])
    for part in parts[root:]:
        folder = folder / part
        init = folder / "__init__.py"
        if not init.exists():
            init.write_text(text)
            written.append(init)
    return written


def _generate_tests(
    by_module: dict[str, list[Symbol]], module: str, test_root: str
) -> tuple[list[str], list[Path]]:
    base = Path(test_root)
    base.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    paths: list[Path] = _write_test_namespace_inits(base)
    for module_name, symbols in sorted(by_module.items()):
        is_root = module_name == module
        # Test files mirror the module name; the root (an __init__.py) becomes
        # test_<root package>. Same-named files are overwritten; custom tests
        # (other names) are left untouched.
        filename = (
            f"test_{module.split('.')[0]}"
            if is_root
            else module_name[len(module) + 1 :]
        )
        path = base / f"{filename}.py"
        path.write_text(_render_test_module(symbols, module, is_root))
        names.append(filename)
        paths.append(path)
    return names, paths


# Each generated test file pairs a mock test (delegation reaches polars, all ops)
# with a "live" test (best-effort real polars: call with no args, skip if it needs
# args, fail only on a genuine leak). _VALUE_LIVE maps value classes we can build a
# real receiver for; namespaces / when-then are mock-only.
_VALUE_LIVE = {"Expr": 'Expr._wrap(pl.col("a"))'}

# Members whose no-arg live call would block on an interactive GUI or otherwise
# misbehave; the mapped string is spliced in as the live-call arguments so the
# "_runs" smoke test stays headless. show_graph defaults to show=True, which
# opens a blocking matplotlib window under a pytest worker.
_LIVE_ARGS = {"show_graph": "show=False"}

# Minimal live-call arguments per hook kind (keyed by hook_name, the same
# taxonomy as _HOOK_SHAPES). A hooked op's smoke test must call the op with
# arguments its hook can actually run against, so adding a new hook to
# _HOOK_SHAPES is all that is needed to cover its generated tests — no per-op
# entry here. The source-frame count comes from _HOOK_SHAPES; the extra source
# frames are spliced in ahead of these keyword arguments.
_HOOK_LIVE_ARGS = {
    "join": 'on="a"',
}


def _live_call(receiver: str, symbol: Symbol) -> str:
    name = _member(symbol)
    if symbol.is_property:
        return f"{receiver}.{name}"
    args = _live_call_args(symbol)
    return f"{receiver}.{name}({args})"


def _live_call_args(symbol: Symbol) -> str:
    name = _member(symbol)
    if symbol.hook_name in _HOOK_SHAPES:
        source_count, _ = _HOOK_SHAPES[symbol.hook_name]
        parts = ["_live_frame()"] * (source_count - 1)
        keywords = _HOOK_LIVE_ARGS.get(symbol.hook_name, "")
        if keywords:
            parts.append(keywords)
        return ", ".join(parts)
    return _LIVE_ARGS.get(name, "")


def _live_test(safe: str, suffix: str, result_stmt: str) -> list[str]:
    return [
        "",
        f"def test_{safe}_{suffix}():",
        "    try:",
        f"        {result_stmt}",
        "    except Exception as exc:  # noqa: BLE001",
        '        if "tableframe:" in str(exc):',
        "            raise  # a real leak, not an argument problem",
        '        pytest.skip(f"not callable with simple args: {type(exc).__name__}")',
        '    assert type(result).__module__.split(".", 1)[0] != "polars"',
    ]


def _render_test_module(symbols: list[Symbol], root: str, is_root: bool) -> str:
    target_class = symbols[0].target_class
    if target_class is None:
        text = _render_functions_test(symbols, root)
    elif is_root:
        text = _render_tableframe_test(symbols, root)
    elif target_class == "LazyGroupBy":
        text = _render_lazygroupby_test(symbols, root)
    else:
        text = _render_value_test(symbols, root)
    return _with_test_marker(text)


def _with_test_marker(text: str) -> str:
    lines = text.splitlines()
    if "import pytest" not in lines:
        future = lines.index("from __future__ import annotations")
        lines.insert(future + 1, "import pytest")
    first_def = next(
        i for i, line in enumerate(lines) if line.startswith(("def ", "@"))
    )
    lines[first_def:first_def] = ["pytestmark = pytest.mark.tfgen", "", ""]
    return "\n".join(lines) + "\n"


def _render_value_test(symbols: list[Symbol], root: str) -> str:
    groups = _group_by_class(symbols)
    multi = (
        len(groups) > 1
    )  # disambiguate test names when a module holds several classes
    has_live = any(class_name in _VALUE_LIVE for class_name in groups)
    relative = symbols[0].target_module[len(root) + 1 :]
    lines = [_test_header(), "from __future__ import annotations", ""]
    if has_live:
        lines += ["import polars as pl", "import pytest"]
    lines += [
        "from unittest.mock import MagicMock",
        "",
        f"from {root}.{relative} import " + ", ".join(groups),
        "",
    ]
    for class_name, class_symbols in groups.items():
        prefix = f"{class_name}_" if multi else ""
        receiver = _VALUE_LIVE.get(class_name)
        for symbol in class_symbols:
            name = _member(symbol)
            safe = f"{prefix}{_safe(name)}"
            lines += ["", f"def test_{safe}_delegates():", "    inner = MagicMock()"]
            if symbol.is_property:
                # The accessor wires straight through to the underlying object.
                lines.append(f"    getattr({class_name}._wrap(inner), {name!r})")
            else:
                argument = "MagicMock()" if name in ("__eq__", "__ne__") else ""
                lines += [
                    f"    getattr({class_name}._wrap(inner), {name!r})({argument})",
                    f"    getattr(inner, {name!r}).assert_called()",
                ]
            if receiver is not None:
                stmt = f"result = {_live_call(receiver, symbol)}"
                lines += _live_test(safe, "runs", stmt)
    return "\n".join(lines) + "\n"


def _render_functions_test(symbols: list[Symbol], root: str) -> str:
    relative = symbols[0].target_module[len(root) + 1 :]
    lines = [
        _test_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "import pytest",
        "from unittest.mock import MagicMock",
        "",
        f"from {root} import {relative} as _module",
        "",
    ]
    for symbol in symbols:
        name = _member(symbol)
        safe = _safe(name)
        lines += [
            "",
            f"def test_{safe}_delegates(monkeypatch):",
            "    spy = MagicMock()",
            f"    monkeypatch.setattr(pl, {name!r}, spy)",
            f"    _module.{name}()",
            "    spy.assert_called()",
        ]
        lines += _live_test(safe, "runs", f"result = {_live_call('_module', symbol)}")
    return "\n".join(lines) + "\n"


def _render_tableframe_test(symbols: list[Symbol], root: str) -> str:
    lines = [
        _test_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "import pytest",
        "",
        f"from {root} import TableFrame",
        f"from {root}._core.hooks import tableframe_of",
        "",
        "",
        "def _live_frame():",
        '    return tableframe_of(pl.LazyFrame({"a": [1.0], "b": [2.0]}))',
    ]
    for symbol in symbols:
        safe = _safe(_member(symbol))
        stmt = f"result = {_live_call('_live_frame()', symbol)}"
        lines += _live_test(safe, "delegates", stmt)
        lines += _live_test(safe, "runs", stmt)
    return "\n".join(lines) + "\n"


def _render_lazygroupby_test(symbols: list[Symbol], root: str) -> str:
    lines = [
        _test_header(),
        "from __future__ import annotations",
        "",
        "import polars as pl",
        "import pytest",
        "from unittest.mock import MagicMock",
        "",
        f"from {root} import TableFrame",
        f"from {root}._core.hooks import tableframe_of",
        f"from {root}._engine.model.frame import TableFrameState",
        f"from {root}.group_by import LazyGroupBy",
        "",
        "",
        "def _group_by():",
        "    grant = {TableFrame._ACCESS_KEY: TableFrame._ACCESS_SECRET}",
        "    parent = TableFrame.__new__(TableFrame, **grant)",
        "    parent._lf = MagicMock()",
        "    parent._state = TableFrameState.empty()",
        "    return LazyGroupBy(MagicMock(), parent, ((), {}))",
        "",
        "",
        "def _live_group_by():",
        "    return tableframe_of(pl.LazyFrame("
        '{"a": [1.0], "b": [2.0]})).group_by("a")',
    ]
    for symbol in symbols:
        name = _member(symbol)
        safe = _safe(name)
        lines += [
            "",
            f"def test_{safe}_delegates():",
            "    group_by = _group_by()",
            f"    group_by.{name}()",
            f"    group_by._lgb.{name}.assert_called()",
        ]
        lines += _live_test(
            safe,
            "runs",
            f"result = {_live_call('_live_group_by()', symbol)}",
        )
    return "\n".join(lines) + "\n"


def _safe(name: str) -> str:
    # Map dunders -> op_<core> so e.g. __abs__ doesn't collide with the method abs.
    if name.startswith("__") and name.endswith("__"):
        return "op_" + name.strip("_")
    return name


