from __future__ import annotations

import json
import sys

from rich import box
from rich.console import Console
from rich.rule import Rule
from rich.table import Table
from rich.text import Text

DELIMITER_STYLE = "bold #2f7fd1"
DETAIL_STYLE = "not bold #8a8a8a"
PROVIDED_STYLE = "green"
DEFAULT_STYLE = "none"
PENDING_MARK = "✗"
PROVIDED_MARK = "✓"
MANDATORY_RULE = "mandatory"
OPTIONAL_RULE = "optional"
DELEGATED_RULE = "delegated"
RULE_STYLES = {
    MANDATORY_RULE: "red",
    OPTIONAL_RULE: "blue",
    DELEGATED_RULE: "dark_orange",
}
COUNTED_RULES = (MANDATORY_RULE, OPTIONAL_RULE)
RULE_LEGENDS = {
    MANDATORY_RULE: "must be provided before creating the instance",
    OPTIONAL_RULE: "can be left unprovided",
    DELEGATED_RULE: "generated by the system if not provided",
}
STATE_LEGENDS = (
    (PENDING_MARK, "pending", None, "no value given yet in any config file"),
    (
        PROVIDED_MARK,
        "provided",
        PROVIDED_STYLE,
        "a value is already given; giving it in one file settles every file",
    ),
)


def token(entry: dict) -> str:
    kind = entry.get("kind", "")
    category = entry.get("category", "")
    if category and category != kind:
        return f"{kind}:{category}"
    return kind


def rule_of(entry: dict) -> str:
    return entry.get("rule", MANDATORY_RULE)


def style_of(entry: dict, style: str | None) -> str:
    return style or RULE_STYLES.get(rule_of(entry), DEFAULT_STYLE)


def section(
    console: Console, entries: list, mark: str, header: str, style: str | None = None
) -> None:
    table = Table(box=box.SIMPLE_HEAD, pad_edge=False, show_edge=False)
    table.add_column(f"{' ' * (len(mark) + 1)}{header}", no_wrap=True)
    table.add_column("Rule", style=DETAIL_STYLE, no_wrap=True)
    table.add_column("Files", style=DETAIL_STYLE, overflow="fold")
    for entry in entries:
        table.add_row(
            Text(f"{mark} {token(entry)}", style=style_of(entry, style)),
            rule_of(entry),
            ", ".join(entry.get("files", [])),
        )
    console.print(table)


def counted(entries: list) -> list:
    return [entry for entry in entries if rule_of(entry) in COUNTED_RULES]


def tally(entries: list) -> str:
    parts = []
    for rule in (MANDATORY_RULE, OPTIONAL_RULE):
        parts.append(f"{sum(1 for e in entries if rule_of(e) == rule)} {rule}")
    return ", ".join(parts)


def render(payload: dict) -> None:
    console = Console()
    instance = payload.get("instance", "")
    stage = payload.get("stage", "")
    folder = payload.get("folder", "")
    pending = payload.get("pending", [])
    provided = payload.get("provided", [])
    show_all = payload.get("all", False)
    notes = payload.get("notes", [])

    title = f"Configuration check — instance '{instance}' ({stage})"
    console.print(Rule(title=title, style=DELIMITER_STYLE, align="left"))
    console.print()
    console.print(f"[{DETAIL_STYLE}]{folder}[/{DETAIL_STYLE}]")
    console.print()

    if pending:
        section(console, pending, PENDING_MARK, "Pending")
    else:
        console.print(f"[{PROVIDED_STYLE}]No pending values.[/{PROVIDED_STYLE}]")
        console.print()

    if show_all and provided:
        if pending:
            console.print()
        section(console, provided, PROVIDED_MARK, "Provided", PROVIDED_STYLE)

    outstanding = counted(pending)
    delegated = len(pending) - len(outstanding)
    pending_style = RULE_STYLES[MANDATORY_RULE]
    summary = f"[{pending_style}]{len(outstanding)} pending[/{pending_style}]"
    if outstanding:
        summary += f"[{DETAIL_STYLE}] ({tally(outstanding)})[/{DETAIL_STYLE}]"
    if delegated:
        summary += (
            f"[{DETAIL_STYLE}] · [/{DETAIL_STYLE}]"
            f"[{RULE_STYLES[DELEGATED_RULE]}]{delegated} {DELEGATED_RULE}"
            f"[/{RULE_STYLES[DELEGATED_RULE]}]"
        )
    if show_all:
        summary += (
            f"[{DETAIL_STYLE}] · [/{DETAIL_STYLE}]"
            f"[{PROVIDED_STYLE}]{len(provided)} provided[/{PROVIDED_STYLE}]"
        )
    console.print()
    console.print(summary)
    console.print()
    legend(console)
    if notes:
        console.print()
        for note in notes:
            console.print(Text(note, style=DETAIL_STYLE))
    console.print(Rule(style=DELIMITER_STYLE))


def legend(console: Console) -> None:
    width = max(
        max(len(rule) for rule in RULE_LEGENDS),
        max(len(f"{mark} {label}") for mark, label, _, _ in STATE_LEGENDS),
    )
    for mark, label, style, description in STATE_LEGENDS:
        line = Text(f"{f'{mark} {label}':<{width}}", style=style or DEFAULT_STYLE)
        line.append(f"   {description}", style=DETAIL_STYLE)
        console.print(line)
    console.print()
    for rule, description in RULE_LEGENDS.items():
        line = Text(f"{rule:<{width}}", style=RULE_STYLES[rule])
        line.append(f"   {description}", style=DETAIL_STYLE)
        console.print(line)


def main() -> int:
    payload = json.load(sys.stdin)
    render(payload)
    return 0


if __name__ == "__main__":
    sys.exit(main())
