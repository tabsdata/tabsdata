use chrono::{Datelike, Local};
use pyo3_stub_gen::{Result, StubInfo};
use std::{
    env,
    fs::{self, File},
    path::{Path, PathBuf},
};

const TD_VCORE_PATH: &str = "TD_VCORE_PATH";
const STUBS_SENTINEL: &str = ".ok.to-pystubs";
const STUB_BANNER: &str = "# This file is automatically generated by pyo3_stub_gen";

const SLASH: &str = "/";
const BACKSLASH: &str = "\\";

fn main() -> Result<()> {
    let sentinel = sentinel();

    let vcore_exists = vcore_available();
    let sentinel_exists = sentinel_available(&sentinel);

    if vcore_exists {
        if sentinel_exists {
            println!(
                "🍎 Variable td_vcore_path exists & sentinel .ok.to-pystubs exists: skipping python stubs generation"
            );

            Ok(())
        } else {
            println!(
                "🍏 Variable td_vcore_path exists & sentinel .ok.to-pystubs does not exist: running python stubs generation"
            );

            let stub = to_foundation::stub_info()?;
            generate(&stub)?;

            if let Some(ref sentinel_path) = sentinel {
                create_home(sentinel_path)?;
                create_sentinel(sentinel_path);
            }

            Ok(())
        }
    } else {
        println!("🍊 Variable td_vcore_path does not exist: running python stubs generation");

        let stub = to_foundation::stub_info()?;
        generate(&stub)?;

        Ok(())
    }
}

//noinspection DuplicatedCode
fn vcore_available() -> bool {
    match env(TD_VCORE_PATH) {
        Some(path) if !path.is_empty() => {
            println!("🍋 Variable td_vcore_path found: '{path}'");
            true
        }
        None => {
            println!("🍋 Variable td_vcore_path missing");
            false
        }
        Some(_) => {
            println!("🍋 Variable td_vcore_path empty");
            false
        }
    }
}

//noinspection DuplicatedCode
fn sentinel_available(sentinel: &Option<PathBuf>) -> bool {
    let Some(file) = sentinel else {
        println!("❗ No sentinel home folder provided");
        return false;
    };
    if file.exists() {
        println!("❗ The sentinel file already exists: '{}'", file.display());
        true
    } else {
        println!("❕ The sentinel file does no exist: '{}'", file.display());
        false
    }
}

//noinspection DuplicatedCode
fn sentinel() -> Option<PathBuf> {
    env::args_os().nth(1).map(|arg| {
        let path = arg.to_string_lossy();

        #[cfg(windows)]
        let path = path.replace(SLASH, BACKSLASH);

        #[cfg(not(windows))]
        let path = path.replace(BACKSLASH, SLASH);

        PathBuf::from(path).join(STUBS_SENTINEL)
    })
}

//noinspection DuplicatedCode
fn create_home(path: &Path) -> Result<()> {
    if let Some(sentinel) = path.parent() {
        fs::create_dir_all(sentinel).map_err(|error| {
            eprintln!(
                "⁉️ Unable to create folder {}: {}",
                sentinel.display(),
                error
            );
            error
        })?;
    }
    Ok(())
}

//noinspection DuplicatedCode
fn create_sentinel(sentinel: &Path) {
    match File::create(sentinel) {
        Ok(_) => println!(
            "🍪 Created sentinel file {}; future python stubs generation runs will be skipped",
            sentinel.display()
        ),
        Err(err) => eprintln!(
            "⁉️ Unable to create sentinel file {}: {}",
            sentinel.display(),
            err
        ),
    }
}

//noinspection DuplicatedCode
fn env(key: &str) -> Option<String> {
    match env::var(key) {
        Ok(value) if !value.is_empty() => Some(value),
        _ => None,
    }
}

//noinspection DuplicatedCode
fn generate(stub: &StubInfo) -> Result<()> {
    let root = stub.default_module_name.as_str();
    let package = root.rsplit_once('.').map_or(root, |(package, _)| package);
    let prefix = format!("{package}.");
    for (name, module) in &stub.modules {
        if name == root || !name.starts_with(&prefix) {
            continue;
        }
        let path = stub
            .python_root
            .join(format!("{}.pyi", name.replace('-', "_").replace('.', "/")));
        let Some(header) = header(&path) else {
            eprintln!(
                "⚠️ Not overwriting hand-written python stub: {}",
                path.display()
            );
            continue;
        };
        if let Some(folder) = path.parent() {
            fs::create_dir_all(folder)?;
        }
        let content = module.format_with_config(stub.config.use_type_statement);
        fs::write(&path, format!("{header}{content}"))?;
        println!("🐍 Generated python stub: {}", path.display());
    }
    Ok(())
}

//noinspection DuplicatedCode
fn header(path: &Path) -> Option<String> {
    let Ok(existing) = fs::read_to_string(path) else {
        return Some(format!(
            "#\n# Copyright {} Tabsdata Inc.\n#\n\n",
            Local::now().year()
        ));
    };
    existing
        .find(STUB_BANNER)
        .map(|start| existing[..start].to_string())
}
