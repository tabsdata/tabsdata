use clap::clap_derive::Parser;
use std::path::PathBuf;

/// Generic worker command line parameters.
/// Arguments for each [crate::launcher::arg::ArgumentKey].
/// Similar to `client/td-sdk/src/main/python/tabsdata/_tabsserver/invoker.py`.
#[derive(Debug, Clone, Parser)]
pub struct ArgumentParameters {
    #[clap(long)]
    /// Counter of the work number for the same function run.
    pub work: String,
    #[clap(long)]
    /// Path of the folder where files with the parameters for the worker are stored.
    pub locks_folder: PathBuf,
    #[clap(long)]
    /// Path of the folder where the log files are stored.
    pub logs_folder: PathBuf,
    #[clap(long)]
    /// Path of the binaries relevant for the worker are placed.
    pub bin_folder: PathBuf,
    #[clap(long)]
    /// Path where the worker request file is placed.
    pub request_folder: PathBuf,
    #[clap(long)]
    /// Path where the worker response file is placed.
    pub response_folder: PathBuf,
    #[clap(long)]
    /// Path of the input folder with input data required by the worker.
    pub input_folder: PathBuf,
    #[clap(long)]
    /// Path of the output folder with the output data generated by the worker.
    pub output_folder: PathBuf,
    #[clap(long)]
    /// Instance name of the Tabsdata server where the code is being executed.
    pub current_instance: PathBuf,
}
