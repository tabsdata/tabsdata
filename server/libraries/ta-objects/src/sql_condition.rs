//! Type-safe, composable SQL WHERE conditions.
//!
//! This module provides a way to build SQL WHERE clauses from strongly-typed
//! Rust values. Each typed value (e.g. `UserId`, `CollectionName`) knows how
//! to turn itself into a `column = value` expression via the [`SeaValue`]
//! trait. `SqlCondition` composes those leaf values into AND/OR trees that
//! ultimately produce a [`sea_query::Condition`].
//!
//! # Key types
//!
//! | Type / Macro | Purpose |
//! |---|---|
//! | [`SqlCondition`] | Core trait — anything that can become a WHERE clause |
//! | [`resolve_condition`] | Turns a `SqlCondition` into a `sea_query::Condition` for a given DAO |
//! | `And![A, B]` / `and!(a, b)` | AND combinator (type-position / value-position) |
//! | `Or![A, B]` / `or!(a, b)` | OR combinator (type-position / value-position) |
//!
//! # How it works
//!
//! 1. **Leaf values** — Or type implementing [`SeaValue`] (generated by the
//!    `#[typed]` proc macro) automatically implements `SqlCondition`. A leaf
//!    produces a single `column = value` expression. The column is resolved at
//!    query time via [`DaoCore::col_for_type`], which maps `TypeId` → column.
//!
//! 2. **Combinators** — `And` and `Or` structs compose conditions:
//!    ```text
//!    and!(Status::Active, Enabled::TRUE)  →  status = 'A' AND enabled = true
//!    or!(Status::Active, Status::Frozen) →  status = 'A' OR  status = 'F'
//!    ```
//!    They nest arbitrarily:
//!    ```text
//!    or!(and!(Status::Active, System::FALSE), and!(Status::Frozen, System::FALSE))
//!    →  (status = 'A' AND system = false) OR (status = 'F' AND system = false)
//!    ```
//!
//! 3. **DAO states** — DAOs define named states as plain inherent fns built
//!    from these combinators via `StateFilter::of`:
//!    ```text
//!    impl FunctionDB {
//!        pub fn available() -> StateFilter<Self> {
//!            StateFilter::of(or!(Status::Active, Status::Frozen))
//!        }
//!    }
//!    ```

use crate::dxo::DaoCore;
use crate::errors::SqlError;
use crate::sea_value::{NullableSeaValue, SeaValue};
use sea_query::{Expr, ExprTrait, IntoTableRef};

// ---------------------------------------------------------------------------
// SqlCondition — core trait
// ---------------------------------------------------------------------------

/// Trait for values that can appear in a SQL WHERE clause.
///
/// Every implementor knows how to turn itself into a [`sea_query::Condition`]
/// by resolving column mappings from the given [`DaoCore`] type `D`. Leaf
/// types produce a single `col = val`; combinators ([`And`](And2) /
/// [`Or`](Or2)) compose children with AND / OR.
pub trait SqlCondition: Send + Sync {
    fn resolve<D: DaoCore>(&self) -> Result<sea_query::Condition, SqlError>;

    /// Whether this condition is the empty "match all rows" predicate
    /// (i.e. `()`). Destructive ops (`delete`, `update`) check this and
    /// refuse to run without a real WHERE clause.
    fn matches_all(&self) -> bool {
        false
    }

    /// Column name → display value pairs for error messages.
    fn display_values<D: DaoCore>(&self) -> Vec<(String, String)> {
        vec![]
    }
}

/// Convenience wrapper: resolves a [`SqlCondition`] into a
/// [`sea_query::Condition`] for the given [`DaoCore`] type `D`.
pub fn resolve_condition<D: DaoCore>(
    condition: impl SqlCondition,
) -> Result<sea_query::Condition, SqlError> {
    condition.resolve::<D>()
}

/// Display values for a single [`SeaValue`] leaf against the given DAO.
pub fn leaf_display_values<D: DaoCore>(sv: &impl SeaValue) -> Vec<(String, String)> {
    if let Some(col) = D::col_for_type(sv.as_type_id()) {
        vec![(sea_query::Iden::to_string(&col), sv.display_value())]
    } else {
        vec![]
    }
}

/// Look up the column that maps to a [`SeaValue`]'s type in the given DAO.
fn col_for_sea_value<D: DaoCore>(sv: &impl SeaValue) -> Result<D::Iden, SqlError> {
    D::col_for_type(sv.as_type_id()).ok_or_else(|| {
        SqlError::TypeNotFound(
            std::any::type_name_of_val(sv).to_string(),
            Box::new(D::table().into_table_ref()),
        )
    })
}

/// Resolves a single [`SeaValue`] leaf to `col = val` for the given DAO.
pub fn resolve_leaf_eq<D: DaoCore>(sv: impl SeaValue) -> Result<sea_query::Condition, SqlError> {
    let col = col_for_sea_value::<D>(&sv)?;
    Ok(sea_query::Condition::all().add(Expr::col(col).eq(sv.as_sea_value())))
}

// ---------------------------------------------------------------------------
// SqlCondition — basic impls
// ---------------------------------------------------------------------------

/// Delegate through references — lets `&T` work.
impl<T: SqlCondition + ?Sized> SqlCondition for &T {
    fn resolve<D: DaoCore>(&self) -> Result<sea_query::Condition, SqlError> {
        (**self).resolve::<D>()
    }

    fn matches_all(&self) -> bool {
        (**self).matches_all()
    }

    fn display_values<D: DaoCore>(&self) -> Vec<(String, String)> {
        (**self).display_values::<D>()
    }
}

/// Unit type produces no filter (matches all rows).
impl SqlCondition for () {
    fn resolve<D: DaoCore>(&self) -> Result<sea_query::Condition, SqlError> {
        Ok(sea_query::Condition::all())
    }

    fn matches_all(&self) -> bool {
        true
    }
}

/// `Option<T>`: `Some(v)` matches `col = v`; `None` matches `col IS NULL`
/// (a bound `= NULL` never matches in SQL, so equality would make a `None`
/// condition unsatisfiable).
impl<T: NullableSeaValue + SqlCondition + 'static> SqlCondition for Option<T> {
    fn resolve<D: DaoCore>(&self) -> Result<sea_query::Condition, SqlError> {
        match self {
            Some(_) => resolve_leaf_eq::<D>(self),
            None => {
                let col = col_for_sea_value::<D>(self)?;
                Ok(sea_query::Condition::all().add(Expr::col(col).is_null()))
            }
        }
    }
}

// ---------------------------------------------------------------------------
// And / Or — explicit AND / OR combinators
// ---------------------------------------------------------------------------

/// Generates a single combinator struct (e.g. `And2` or `Or3`) with its
/// `SqlCondition` impl. Parametrized on `$Name` (And/Or) and `$cond_fn`
/// (all/any) so the same macro handles both AND and OR variants.
macro_rules! define_combinator {
    ($Name:ident, $cond_fn:ident, $n:tt, $($T:ident),+) => {
        paste::paste! {
            #[derive(Debug, Clone)]
            pub struct [<$Name $n>]<$($T),+>($(pub $T),+);

            #[allow(non_snake_case)]
            impl<$($T: SqlCondition),+> SqlCondition for [<$Name $n>]<$($T),+> {
                fn resolve<D: crate::dxo::DaoCore>(&self) -> Result<sea_query::Condition, crate::errors::SqlError> {
                    let [<$Name $n>]($($T),+) = self;
                    let mut cond = sea_query::Condition::$cond_fn();
                    $(cond = cond.add($T.resolve::<D>()?);)+
                    Ok(cond)
                }

                fn display_values<D: crate::dxo::DaoCore>(&self) -> Vec<(String, String)> {
                    let [<$Name $n>]($($T),+) = self;
                    let mut values = Vec::new();
                    $(values.extend($T.display_values::<D>());)+
                    values
                }
            }
        }
    };
}

/// Generates `AndN` + `OrN` structs and their `SqlCondition` impls.
macro_rules! define_and_or {
    ($n:tt, $($T:ident),+) => {
        define_combinator!(And, all, $n, $($T),+);
        define_combinator!(Or, any, $n, $($T),+);
    };
}

define_and_or!(1, T);
define_and_or!(2, T1, T2);
define_and_or!(3, T1, T2, T3);
define_and_or!(4, T1, T2, T3, T4);

/// Type-position macro: `And![A, B]` → `And2<A, B>`.
#[allow(non_snake_case)]
#[macro_export]
macro_rules! And {
    ($t:ty $(,)?) => { $crate::sql_condition::And1<$t> };
    ($t1:ty, $t2:ty $(,)?) => { $crate::sql_condition::And2<$t1, $t2> };
    ($t1:ty, $t2:ty, $t3:ty $(,)?) => { $crate::sql_condition::And3<$t1, $t2, $t3> };
    ($t1:ty, $t2:ty, $t3:ty, $t4:ty $(,)?) => { $crate::sql_condition::And4<$t1, $t2, $t3, $t4> };
}

/// Type-position macro: `Or![A, B]` → `Or2<A, B>`.
#[allow(non_snake_case)]
#[macro_export]
macro_rules! Or {
    ($t:ty $(,)?) => { $crate::sql_condition::Or1<$t> };
    ($t1:ty, $t2:ty $(,)?) => { $crate::sql_condition::Or2<$t1, $t2> };
    ($t1:ty, $t2:ty, $t3:ty $(,)?) => { $crate::sql_condition::Or3<$t1, $t2, $t3> };
    ($t1:ty, $t2:ty, $t3:ty, $t4:ty $(,)?) => { $crate::sql_condition::Or4<$t1, $t2, $t3, $t4> };
}

/// Value-position macro: `and!(a, b)` → `And2(a, b)`.
#[macro_export]
macro_rules! and {
    ($e:expr $(,)?) => {
        $crate::sql_condition::And1($e)
    };
    ($e1:expr, $e2:expr $(,)?) => {
        $crate::sql_condition::And2($e1, $e2)
    };
    ($e1:expr, $e2:expr, $e3:expr $(,)?) => {
        $crate::sql_condition::And3($e1, $e2, $e3)
    };
    ($e1:expr, $e2:expr, $e3:expr, $e4:expr $(,)?) => {
        $crate::sql_condition::And4($e1, $e2, $e3, $e4)
    };
}

/// Value-position macro: `or!(a, b)` → `Or2(a, b)`.
#[macro_export]
macro_rules! or {
    ($e:expr $(,)?) => {
        $crate::sql_condition::Or1($e)
    };
    ($e1:expr, $e2:expr $(,)?) => {
        $crate::sql_condition::Or2($e1, $e2)
    };
    ($e1:expr, $e2:expr, $e3:expr $(,)?) => {
        $crate::sql_condition::Or3($e1, $e2, $e3)
    };
    ($e1:expr, $e2:expr, $e3:expr, $e4:expr $(,)?) => {
        $crate::sql_condition::Or4($e1, $e2, $e3, $e4)
    };
}

// ---------------------------------------------------------------------------
// Lte — less-than-or-equal comparison
// ---------------------------------------------------------------------------

/// Less-than-or-equal condition: produces `col <= val`.
///
/// Works like a leaf [`SqlCondition`] but uses `<=` instead of `=`:
/// ```text
/// and!(table_id, lte!(triggered_on))  →  table_id = ? AND triggered_on <= ?
/// ```
#[derive(Debug, Clone)]
pub struct Lte<T>(pub T);

impl<T: SeaValue> SqlCondition for Lte<T> {
    fn resolve<D: DaoCore>(&self) -> Result<sea_query::Condition, SqlError> {
        let col = col_for_sea_value::<D>(&self.0)?;
        Ok(sea_query::Condition::all().add(Expr::col(col).lte(self.0.as_sea_value())))
    }
}

/// Value-position macro: `lte!(a)` → `Lte(a)`.
#[macro_export]
macro_rules! lte {
    ($e:expr) => {
        $crate::sql_condition::Lte($e)
    };
}

// ---------------------------------------------------------------------------
// Not — negation wrapper
// ---------------------------------------------------------------------------

/// Negation condition: produces `NOT (inner_condition)`.
///
/// Wraps any [`SqlCondition`] and negates it:
/// ```text
/// and!(table_id, not!(status))  →  table_id = ? AND NOT (status = ?)
/// ```
#[derive(Debug, Clone)]
pub struct Not<T>(pub T);

impl<T: SqlCondition> SqlCondition for Not<T> {
    fn resolve<D: DaoCore>(&self) -> Result<sea_query::Condition, SqlError> {
        Ok(self.0.resolve::<D>()?.not())
    }

    fn display_values<D: DaoCore>(&self) -> Vec<(String, String)> {
        self.0.display_values::<D>()
    }
}

/// Type-position macro: `Not![T]` → `Not<T>`.
#[allow(non_snake_case)]
#[macro_export]
macro_rules! Not {
      ($t:ty $(,)?) => { $crate::sql_condition::Not<$t> };
  }

/// Value-position macro: `not!(a)` → `Not(a)`.
#[macro_export]
macro_rules! not {
    ($e:expr) => {
        $crate::sql_condition::Not($e)
    };
}
