//! Mint the three per-project roles (`<name>_admin`, `<name>_dev`,
//! `<name>_view`) when a project is created, and add the creating user to
//! `<name>_admin`.
//!
//! Per-project, system-managed roles: each role is a
//! system-managed role (`fixed = true`) carrying exactly one fixed permission
//! on the new project — `manage_project` / `develop_project` / `view_project`
//! respectively. Membership, by contrast, is user-managed (governed by
//! `manage_project` on the project), so the creator's `<name>_admin` membership
//! row is **not** fixed.
//!
//! Runs after `seed_default_groups`, inside the project-create transaction, so
//! the `projects` row already exists (the `roles.project_id` FK is satisfied)
//! and `ProjectId` is in context.

use std::ops::Deref;
use td_database::dynamic::DynamicConnection;
use td_error::TdError;
use td_objects::dxo::crudl::RequestContext;
use td_objects::dxo::permission::{PermissionDB, PermissionDBBuilder};
use td_objects::dxo::project::ProjectCreateDB;
use td_objects::dxo::role::{RoleCreate, RoleDB, RoleDBBuilder};
use td_objects::dxo::user_role::UserRoleDB;
use td_objects::types::basic::{
    Description, EntityId, Fixed, PermissionEntityType, PermissionType, ProjectId, ProjectName,
    RoleKind, RoleName,
};
use td_objects::{Buildable, Setter, TryUpdater};
use td_queries::LiveEntry;
use td_tower::extractors::{MutRef, Ref};

/// The three per-project roles minted for every project, in
/// (kind, name suffix, permission, description template) form.
const PER_PROJECT_ROLES: [(RoleKind, &str, PermissionType, &str); 3] = [
    (
        RoleKind::ProjectAdmin,
        "admin",
        PermissionType::ManageProject,
        "Project {name} administrators",
    ),
    (
        RoleKind::ProjectDev,
        "dev",
        PermissionType::DevelopProject,
        "Project {name} developers",
    ),
    (
        RoleKind::ProjectView,
        "view",
        PermissionType::ViewProject,
        "Project {name} viewers",
    ),
];

/// Derive a per-project role name `<project>_<suffix>` and parse it through the
/// `RoleName` parser. The project name is already a valid identifier
/// (`[A-Za-z][A-Za-z0-9_]*`), and `RoleName` shares that grammar, so
/// `<project>_admin` etc. always parse — but we surface any parser rejection
/// rather than weaken the parser.
fn per_project_role_name(project: &ProjectName, suffix: &str) -> Result<RoleName, TdError> {
    RoleName::try_from(format!("{project}_{suffix}"))
}

pub async fn seed_project_roles(
    mut conn: MutRef<DynamicConnection<'static>>,
    context: Ref<RequestContext>,
    project_id: Ref<ProjectId>,
    project: Ref<ProjectCreateDB>,
) -> Result<(), TdError> {
    let project_id = *project_id.deref();
    let project_name = &project.name;
    // The new project as a permission target entity.
    let entity_id = EntityId::try_from(project_id)?;

    let mut admin_role_id = None;
    for (kind, suffix, permission_type, description_tmpl) in PER_PROJECT_ROLES {
        let is_admin = matches!(kind, RoleKind::ProjectAdmin);
        let role_name = per_project_role_name(project_name, suffix)?;
        let description =
            Description::try_from(description_tmpl.replace("{name}", &project_name.to_string()))?;

        // Build the role: system-managed (`fixed = true`), kind set, bound to
        // the new project. The id is generated by the builder default.
        let role_create = RoleCreate::builder()
            .name(role_name)
            .description(description)
            .build()?;
        let role = RoleDBBuilder::try_from(&role_create)?
            .try_update_from(context.deref())?
            .kind(kind)
            .project_id(Some(project_id))
            .fixed(Fixed::from(true))
            .build()?;

        // The role's single fixed permission on the new project.
        let permission = PermissionDBBuilder::default()
            .try_update_from(context.deref())?
            .try_update_from(&role)?
            .permission_type(permission_type)
            .entity_type(PermissionEntityType::Project)
            .entity_id(entity_id)
            .fixed(Fixed::from(true))
            .build()?;

        conn.live().insert::<RoleDB>(&role).await?;
        conn.live().insert::<PermissionDB>(&permission).await?;

        if is_admin {
            admin_role_id = Some(role.id);
        }
    }

    // Add the creating user to `<name>_admin`. Per-project membership is
    // user-managed (governed by `manage_project` on the project), so this
    // membership row is NOT fixed — it can be added/removed later by any
    // `manage_project` holder.
    let admin_role_id = admin_role_id.expect("ProjectAdmin role minted above");
    let user_role = UserRoleDB::builder()
        .try_update_from(context.deref())?
        .set(&context.user_id)
        .set(&admin_role_id)
        .fixed(Fixed::from(false))
        .build()?;
    conn.live().insert::<UserRoleDB>(&user_role).await?;

    Ok(())
}
